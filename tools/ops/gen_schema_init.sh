#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=db/schema-init.sql
{
  echo "-- ====================================================================="
  echo "-- testPike fresh-install bootstrap (one-shot init for a brand-new database)"
  echo "-- Generated by merging db/migration/V1..V* in version order (sort -V),"
  echo "--           plus a trailing patch section for objects first applied by hand."
  echo "-- Use: auto-runs from docker-entrypoint-initdb.d on an empty volume, or psql -v ON_ERROR_STOP=1 -f."
  echo "-- Never run this on an existing database; upgrades replay db/migration/ incrementally."
  echo "-- Maintenance: rerun tools/ops/gen_schema_init.sh after adding a migration (idempotent; do not hand-edit this artifact)."
  echo "-- ====================================================================="
  echo
  for f in $(git ls-files db/migration | sort -V); do
    echo "-- ################ $(basename "$f") ################"
    cat "$f"
    echo
  done
  echo "-- ################ patch section: objects first executed by hand (DDL verified against the dev database, never captured as migrations) ################"
  cat <<'EOF'
CREATE SEQUENCE IF NOT EXISTS tp_plan_deviation_id_seq;
CREATE TABLE IF NOT EXISTS tp_plan_deviation (
    id             BIGINT NOT NULL DEFAULT nextval('tp_plan_deviation_id_seq'),
    plan_id        BIGINT       NOT NULL,
    case_id        BIGINT       NOT NULL,
    deviation_type SMALLINT     NOT NULL,
    reason         VARCHAR(500) NOT NULL,
    created_by     BIGINT       NOT NULL,
    created_at     TIMESTAMP    DEFAULT NOW(),
    CONSTRAINT tp_plan_deviation_pkey PRIMARY KEY (id)
);
ALTER SEQUENCE tp_plan_deviation_id_seq OWNED BY tp_plan_deviation.id;
ALTER TABLE tp_exec_plan ADD COLUMN IF NOT EXISTS lock_mode SMALLINT NOT NULL DEFAULT 1;
EOF
} > "$OUT"
# ── Displayed-description wash stage : historical migrations stay
# untouched, but every tp_sys_config.description literal in the generated bootstrap
# must carry no internal bookkeeping ids. The deterministic replacement table is
# tools/config_desc_wash.json (tracked input: old literal -> new operator-facing
# text), so fresh installs match the dev DB exactly. Idempotent: washed output
# contains no old literals, re-running changes nothing.
python3 - "$OUT" <<'PYEOF'
import json, sys
out = sys.argv[1]
wash = json.load(open("tools/config_desc_wash.json", encoding="utf-8"))
# longest-first so no short literal shadows a longer one
pairs = sorted(wash.items(), key=lambda kv: -len(kv[0]))
with open(out, encoding="utf-8") as fh:
    text = fh.read()
n = 0
for old, new in pairs:
    if old in text:
        n += text.count(old)
        text = text.replace(old, new)
with open(out, "w", encoding="utf-8") as fh:
    fh.write(text)
print(f"desc wash applied: {n} seed literals")
PYEOF
echo "generated $OUT ($(grep -c . "$OUT")  lines, $(du -h "$OUT" | cut -f1))"

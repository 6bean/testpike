package com.sixbean.testpike.core.aichat.domain.service.impl;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.sixbean.testpike.common.exception.BizErrorCode;
import com.sixbean.testpike.common.exception.ServiceException;
import com.sixbean.testpike.core.aichat.domain.component.DraftObjectType;
import com.sixbean.testpike.core.aichat.domain.component.DraftPayloadReads;
import com.sixbean.testpike.core.aichat.domain.component.DraftLandContext;
import com.sixbean.testpike.core.aichat.domain.service.ChatSessionService;
import com.sixbean.testpike.core.aichat.domain.service.DraftWriteStrategy;
import com.sixbean.testpike.core.testreport.api.dto.ReportGenerateInput;
import com.sixbean.testpike.core.testreport.api.dto.ReportRecordInfo;
import com.sixbean.testpike.core.testreport.domain.service.TestReportService;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

import java.util.Map;

/**
 * Test-report-landing strategy behind the generic draft door (tool-surface
 * clearing batch stage 4c, seventh cleared domain): one confirmed dialog
 * proposal generates a summary report through the SAME TestReportService
 * .generate chain the report page's generate dialog uses — the range-type
 * refusal, the plan-must-exist-and-belong-to-the-project check, the missing
 * time-window refusal, the aggregation itself, the row insert and audit all
 * come free, never a parallel write path (red line: no second report save).
 * <p>The report keeps its human lifecycle after landing: exporting (xlsx/pdf)
 * and deleting a report stay deliberate human clicks on /test-report;
 * confirming a dialog card is never an export.
 * <p>Attribution guard (H1): the owning project comes from the SESSION, never
 * from the payload — a model-forged projectId is simply not consumed; the
 * report is generated by (and attributed to) the human who confirmed the
 * card. The plan id named in the payload is re-checked by TestReportService
 * against that project, so a cross-project plan id cannot smuggle someone
 * else's scope into the snapshot.
 * <p>Only the kind's own anchors are validated here; every business rule
 * (range legality, plan ownership, title defaulting) stays single-sourced in
 * TestReportServiceImpl — a payload it rejects surfaces in its own
 * human-readable wording, never reworded into a second spectrum.
 */
@Service
public class ReportWriteDraftStrategy implements DraftWriteStrategy {

    private final TestReportService testReportService;
    private final ChatSessionService sessionService;
    private final JdbcTemplate jdbcTemplate;
    private final ObjectMapper objectMapper = new ObjectMapper();

    public ReportWriteDraftStrategy(TestReportService testReportService,
                                    ChatSessionService sessionService,
                                    JdbcTemplate jdbcTemplate) {
        this.testReportService = testReportService;
        this.sessionService = sessionService;
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public String objectType() {
        return DraftObjectType.REPORT_WRITE.wireName;
    }

    @Override
    public Integer land(Map<String, Object> draftRow, long operatorId) {
        DraftLandContext ctx = DraftLandContext.open(draftRow, sessionService, objectMapper,
                "AI 报告草案内容无法解析，确认写入已拒绝（请重新让 AI 生成提案）");
        JsonNode body = ctx.body();
        long draftId = ctx.draftId(), sessionId = ctx.sessionId(), projectId = ctx.projectId();
        int rangeType = body.path("rangeType").asInt(0);
        Long planId = body.hasNonNull("planId") ? body.get("planId").asLong() : null;
        String startTime = DraftPayloadReads.text(body, "startTime");
        String endTime = DraftPayloadReads.text(body, "endTime");
        String title = DraftPayloadReads.text(body, "title");
        // The generate chain re-checks the anchors itself (plan existence and
        // ownership for rangeType=1, the non-blank window for rangeType=2);
        // this strategy only refuses a body that cannot even reach it.
        if (rangeType != 1 && rangeType != 2) {
            throw new ServiceException(
                    "AI 报告草案缺少合法的报告范围 rangeType（1=按计划 2=按时间范围），无法生成报告——请在「AI 对话」写明范围类型与取值后重新生成提案；也可在「总结报告」页直接生成",
                    BizErrorCode.VALIDATION_ERROR);
        }
        ReportRecordInfo created = testReportService.generate(operatorId,
                new ReportGenerateInput(projectId, rangeType, planId, startTime, endTime, title));
        jdbcTemplate.update("UPDATE tp_ai_chat_draft SET target_id = ?, updated_at = now() "
                + "WHERE id = ?", created.id(), draftId);
        // A create has no separate applied version for this kind (null = none).
        return null;
    }

}

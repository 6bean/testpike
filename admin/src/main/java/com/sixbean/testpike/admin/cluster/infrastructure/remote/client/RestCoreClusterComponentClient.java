package com.sixbean.testpike.admin.cluster.infrastructure.remote.client;

import com.sixbean.testpike.admin.auth.app.component.UserContext;
import com.sixbean.testpike.admin.cluster.api.dto.ClusterComponentView;
import com.sixbean.testpike.common.client.RestClientInvoker;
import com.sixbean.testpike.common.clientobject.Response;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.ParameterizedTypeReference;
import org.springframework.http.HttpMethod;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;

import java.util.List;


@Component
public class RestCoreClusterComponentClient implements CoreClusterComponentClient {

    private final RestClient rest;

    public RestCoreClusterComponentClient(@Value("${core.base-url:http://localhost:8083}") String coreBaseUrl) {
        this.rest = RestClientInvoker.defaultRestClient(coreBaseUrl);
    }

    @Override
    public List<ClusterComponentView> listComponents() {
        return RestClientInvoker.call(rest, HttpMethod.GET, "/internal/cluster/components", null,
                new ParameterizedTypeReference<Response<List<ClusterComponentView>>>() {
                }, UserContext.currentUserId());
    }
}

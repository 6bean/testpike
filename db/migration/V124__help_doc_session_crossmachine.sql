## 这一页能做什么
当执行机器不止一台时，让「先登录、再跑后续步骤」的用例不必每台机器都重新登录：一台机器登录拿到的会话凭据，其它机器接着用；对必须回到原机器续跑的用例，系统会自动把任务派回那台机器。

## 怎么用
1. **免登录续跑（默认可跨机）**：在用例的登录步骤里，把要传递的会话凭据（如令牌）声明为会话工件并起一个名字；后续步骤直接引用这个名字即可。批次跑起来后，凭据会安全地随批次流转，任何一台在线机器领到任务都能接着用，不需要重复登录。
2. **必须回原机器（粘机模式）**：有些被测系统换了 IP 就会话失效。在登录步骤的会话工件声明里选择「粘机」，该用例的后续任务就只派给持有这份凭据的那台机器。
3. **凭据失效怎么办**：如果凭据过期或被被测系统拒绝，执行会如实失败并提示「会话工件失效，重登续跑」——不静默硬撑，重跑登录步骤即可恢复。

## 操作背后系统做了什么
- 回传的会话凭据全程加密保存，按批次隔离；只有领取该批次任务的执行器会拿到，且校验领取令牌防止伪造回传，试运行任务不属于任何批次因此不允许回传。
- 选择「粘机」的后续任务，派发时先看这份凭据的租约：租约还在有效期内且属于别的机器，这台机器就把任务让出去排队等待，不抢跑；租约到期（长时间没续用）就自动恢复自由派发，任务不会被饿死。
- 凭据保留时长和租约时长都由管理员在系统配置中调整，改完即时生效，不需要重启。

## 常见问题
- 为什么我的任务一直不被领取？——多半是它声明了「粘机」且原持有机器还在线，任务在排队等它；原机器下线或租约过期后会自动分给其它机器。
- 多台机器会重复登录吗？——不会。凭据回传后同批次其它机器直接复用；只有工件确认失效时才需要重跑登录步骤。

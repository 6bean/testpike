一条完整动线：顶栏切到项目集 → 新建旅程 → 段表编辑页逐段钉选所属项目与已发布资产（或用例集）→ 调整段先后顺序 → 点「发起运行」→ 系统按段顺序展开各项目执行批次 → 时间线页逐段红绿灯自动跟随 → 全部段进入终态后由旅程负责人准出签字。

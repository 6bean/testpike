执行器池回答「跑用例的机器怎么编组、容量给谁用、会不会所有项目抢同一批机器」。每个池列出成员机、容量与当前占用水位，以及被哪些项目使用；批次派发按池路由，容量满时任务排队而不是丢。开启弹性伸缩的池还会显示期望副本与当前副本、待派发任务数与等待时长，并自动加机器或减机器，伸缩的每一次动作与原因都记在页面的伸缩事件时间线里。管理员在本页做四件事：编组成员、看水位决定扩容、给项目换池、开关并核查弹性伸缩；测试负责人发起批次前也可以来这里确认自己项目绑定的池当下是否空闲，避免任务提交后长时间排队。

## 总体流程
动线：执行器自动注册并心跳上报（事实源） → 编组入池（机器按能力进池） → 项目挂池（归属在项目侧配置） → 派发路由（按能力与池归属选机） → 水位监控（占用高就扩容或换池） → 弹性伸缩（开启后系统按积压自动加减机器，动作带护栏并记入时间线）。
- 池是视图不是机器：机器在线与自检状态在执行侧看，池只决定「谁优先给谁跑」；机器本身故障时先修机器，编组帮不上忙。
- 派发永远先保任务不丢：容量满了排队，不静默失败；排队时长在批次控制台可回查。
- 扩容与分流两条路等价：加机器入池，或把部分项目换到空闲池；判断依据就是本页的水位条与池成员能力构成。
- 弹性伸缩是自动档：开启后系统定期按「待派发数量＋等待时长＋池余量＋预算水位」决定期望副本数；不开启的池维持人工管理。

## 怎么用（按操作顺序）
1. **看全局水位**：列表逐个池显示名称、成员数、总容量与当前占用；水位条是最直观的扩容信号。决定动作前先核对项目实际绑定的是哪个池——同名池容易看串，绑定关系以项目侧配置为准，本页只呈现机器侧的占用事实。
2. **查池内机器**：点进池看成员机清单与每台的能力标签（Web/APP/接口），确认这台机器能不能跑你要的任务类型；节点矩阵里每台机器还带版本徽标，红黄绿三色直接看出谁落后于目标版本。
3. **编组调整**：点「编组」把执行器拉进或移出池；池与项目的归属关系在项目侧配置，本页管机器侧。
4. **处理拥堵**：某池水位持续顶格，三个选择——开启弹性让系统自动加机器、手动扩容（加机器入池）、或让部分项目换到空闲池；调整后新批次立即按新池路由。
5. **回查排队**：批次派发后在执行侧看到排队与开跑时间；怀疑容量问题时，先确认执行器在线与自检通过，再回本页调池。排队持续变长而水位不高时，优先看池成员的能力构成是不是和任务类型不匹配，容量数字本身不说明问题。
6. **核查弹性**：池卡片的弹性区显示期望副本、当前副本、待派发、等待 P95 与弹性健康状态；「伸缩事件时间线」按时间倒序列出每一次扩容或缩容的动作、副本变化与原因句。怀疑机器数不对时先看这里的原因，再看顶部的弹性健康灯。

## 操作背后系统做了什么
- 执行器注册与心跳是事实源：机器掉线超过心跳阈值自动视为不可派发，池视图上相应减容，无需人工摘除。
- 派发按「能力匹配 + 池归属 + 当前占用」三步路由：先过滤能跑该任务类型的机器，再限定在项目绑定的池内，最后选占用最低的机器；容量满时任务排队，不丢不失败。
- 水位=已派发未完成任务数与机器并发上限之比，取数来自心跳上报的实时状态；把项目从满池换到空池，只影响之后的新派发。
- 机器移出池不影响它正在执行的任务，跑完自然交接；新任务即刻不再路由到该机器。
- 能力标签决定可跑的任务类型：Web 引擎、APP 引擎、接口任务各走各的匹配，混编池不会让 APP 任务落到只有 Web 能力的机器上。
- 心跳超时即减容：机器掉线超过阈值后从可派发集摘除，水位分母同步变小；机器恢复并完成自检后自动回填，不需要管理员手动重新编组。
- 弹性伸缩每轮评估：系统按待派发任务数、等待时长 P95、池内余量与预算水位算出期望副本数，再和当前副本比较得出「扩容 / 缩容 / 保持」；伸缩动作受三道护栏约束——池的最小与最大副本边界、两次伸缩之间的冷却间隔、缩容前先排空机器上在跑的任务（不会打断执行中的用例）。
- 预算吃紧时自动暂停：当预算水位超过设定比例，弹性伸缩会暂停加机器并在伸缩事件里写明暂停原因，预算回落后自动恢复；暂停期间你仍可手动扩容。
- 每次伸缩动作都留账：动作、前后副本数与原因句按时间记入伸缩事件，页面时间线与后台记录读同一份账，不会出现两个数字。

## 常见问题
- **池里没有可用机器怎么办？**——先到执行侧看机器在线与自检状态：机器不在线时编组帮不上忙，先恢复机器再回本页调整归属。
- **水位一直顶格会影响什么？**——新批次任务排队等待派发，批次控制台可见排队时长；持续顶格就该开弹性或扩容分流，不是让执行器硬扛。
- **把机器移出池，正在跑的任务会中断吗？**——不会，在跑任务自然收尾；移出只对新派发生效。弹性缩容同样先排空再减机，逻辑一致。
- **刚接入的机器为什么没进可派发集？**——新机器需完成注册、心跳与自检后才进入可派发集；若长时间未出现，先查该机的执行器进程与网络。

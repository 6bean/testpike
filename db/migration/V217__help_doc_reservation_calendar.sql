## 这一页能做什么
跑 APP 自动化前最怕「到了要用的时间点设备被别人占着」。这一页把每台设备的时间排布画成日历泳道：每台设备一道横条，条上的色块就是已经被预约的时间窗；你按住鼠标在泳道上拖一段，就是在说「这段时间我要用这台机器」。入口：左侧菜单「APP 自动化 → 设备预约日历」。

## 怎么用（按操作顺序）
1. **选项目定窗口**：右上角选定项目（日历按项目隔离），时间窗口默认展示「最近一小时到未来一天」，也可以用时间范围选择器看更长。
2. **拖拽建预约**：在某台设备的泳道上按住拖动圈出时间段（自动吸附到 15 分钟刻度），松手后弹出确认框，选好设备、核对起止时间、写清事由后提交。不方便拖拽时，点右上角「新建预约」效果一样。
3. **看冲突**：如果你圈的时间段和已有预约重叠，系统会当场拒绝并明确告诉你「这台机器该时段已被谁预约、到什么时候」——照提示换个时间段或换台设备即可。开了审批的项目，新预约会先进「待审批」，页面标题旁的角标就是待审批条数。
4. **管理自己的预约**：页面下方「我的预约」卡汇总你名下所有预约；点任何色块打开详情，可以取消预约，用完了点「提前归还」把时间窗让给别人。
5. **审批**：项目管理员在待审批色块（黄色）的详情里点「批准」或「驳回」；驳回必须写理由，预约人会立刻收到站内通知。
6. **配合批次使用**：在批次详情页的「关联设备预约」卡里，可以把这个批次绑到某条预约上（或解绑）。绑了预约的批次，派发时会优先只用预约里圈好的那台设备、只在预约时间窗内跑。

## 操作背后系统做了什么
- 时间窗是否冲突，由服务端按「开始含、结束不含」的半开区间逐台核对，同一台设备的两段预约只要有任何重叠就会被拒；提示里的「预计释放时间」取的是该设备上正在跑的任务的预计结束点，两个值取更晚的一个，保证给你的建议是真能用的。
- 日历上的「实际占用条」（红色细条）来自执行器的真实租约记录，不是预约推算——预约只代表计划，占用才代表现在这台机器在谁手里，两者分开展示不混算。
- 超过时间窗还没用的预约会被后台定时任务自动释放（生效中的超时预约同样回收），并给预约人发站内通知；审批通过、驳回、超时释放三类结果都有通知，不用守在页面刷新等。
- 批次绑定预约时服务端会核对批次和预约属于同一个项目，跨项目绑定直接拒绝并点名两边的归属；已经归还或取消的预约不允许再改绑定。
- 预约只管「计划」，真正开跑那一刻设备是否可用仍由执行租约定夺——所以即使日历上空着，开工瞬间被临时任务占用也是可能的，此时批次会按排队机制等待，不会拿别人的占用数据凑数。

## 常见问题
- 为什么我圈完松手提示「已被某某预约」？——那段时间该设备已有他人预约；详情色块上能看到预约人和时间，商量错开或换一台设备。
- 黄色块和蓝色块什么区别？——黄色=待审批（需要项目管理员点批准才生效），蓝色=已生效。审批开关由管理员在系统设置里控制，关闭时新预约直接生效。
- 预约到期会自动怎样？——过了结束时间仍未使用/未归还的预约会被后台自动释放，你会收到站内通知；请提前归还把时间段让出来。
- 批次一定要绑预约吗？——不绑也能跑（按普通排队选机）；绑了预约就是「这段时间这台机器专门为这个批次留的」，适合发版前固定时段的回归。

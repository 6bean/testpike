 '## 这一页能做什么
一次 AI 评测 = 一套考卷（评测集版本）×一把尺（裁判标准 Rubric 版本）×一个被测目标（自家生成配置或外部被测 AI 系统）×一个裁判模型。这一页负责发起评测、跟踪每次运行的状态（待派发/进行中/已完成/失败），并跳转报告。入口：左侧菜单「AI 评测运行」。

## 怎么用（按操作顺序）
1. 点「发起评测」：选定「已发布的评测集版本」与「裁判标准」，被测目标二选一——自家生成配置（评平台自己的 AI 产出）或被测 AI 系统（接入的外部对象），填写引用参数后创建。
2. 新建运行停在「待派发」：本页「派发评测」把它交给评测引擎排队执行（派发口独立，防止误触发一轮昂贵评测）。
3. 跟踪状态：列表按名称/状态筛选；「进行中」的运行可稍后刷新查看，完成后点「查看报告」直达评分明细。
4. 每次运行都会冻结当次的标准快照与评测集摘要——事后修改 Rubric 或发布新样本版本，不会改写历史运行的归因。

## 操作背后系统做了什么
- 评测运行由服务端逐条样本调用裁判模型打分（规则分+模型分+每维理由与证据引用），token 与成本逐条入账，报告页的成本卡读的就是这本账。
- 裁判标准版本与评测集版本都在创建时定格（快照落库），列表里显示的「评测集版本/裁判标准」即那次运行的实际依据。
- 敏感标记样本的送审约束在派发口生效：未过审敏感样本禁送外部厂商裁判，只走内部模型。


$hb616$## 这一页能做什么
页面元素集中建档之后，日常最常被问住的两件事是：页面改版了没有？这次跑绿是被系统自动救回来的，还是真的稳？本能力把这些信号直接摆到屏幕上：执行报告里，凡原本定位锚打空、由系统换成等效锚后命中的步骤，行上带「自愈命中」徽标，批次汇总把「自愈命中率」与「断言失配」两个数并排显示；「页面元素库」页顶部有健康看板，改版风暴卡把同一时间窗内一起变陈旧的元素按页面归成一张卡，「将坏」徽标和铃铛通知在元素彻底失效之前先打招呼；列表「健康度」列以红黄绿展示每条档案最近的表现。解决的典型业务问题：改版总是先用例失败才暴露、没有提前量；自愈兜住了多少锚的漂移没人说得清；不知道该优先修哪一页的定位锚。

## 总体流程
执行落空 → 等效备用锚自动重定位（报告行亮「自愈命中」徽标）→ 命中与落空计入滚动健康账 → 健康度转黄转红、连续两窗恶化标记「将坏」并发铃铛 → 同窗内成批变陈旧聚合成「改版风暴」卡 → 按卡到执行中心发起批量试运行 → 逐条修订或退役定位锚
看板和徽标只改变「看得见什么」，不改变任何用例结果：自愈只允许等效重定位；断言类步骤永不自动自愈；执行失败照旧走失败归因，不会被徽标掩盖。

## 怎么用（按操作顺序）
1. **看跑得怎么样**：打开批次执行记录，原锚打空、换锚命中的步骤行旁显示「自愈命中」徽标，点开可看新旧定位表达式；批次行上「自愈命中率 {x}（触达 {a}/{b} 步）· 断言失配 {c} 步」两个数要并读——命中率稳而证据数攀升，说明页面改版正靠自愈兜住，该去修锚了。
2. **看每条档案的状态**：进「页面元素库」，列表「健康度」列每条显示「健康」「注意」「高风险」「未触达」之一，恶化趋势另带「将坏」徽标；「未触达」表示滚动窗口内没有执行触达记录，不是坏了。
3. **看整页的风暴与预警**：元素库页顶部健康看板中，「改版风暴」卡一页一张，「已陈旧」与「将坏」两列并排不混计；「自愈命中」卡展示命中率与近期自愈证据数；「批量试运行建议」卡列出受影响条目，按提示到「执行中心」发起批量回归试运行，验证改版后引用这些元素的脚本仍可运行。
4. **收铃铛通知**：某元素未命中率连续两个统计窗口上升且未全灭时，系统把它标记将坏并投递铃铛通知，标题点名「页面元素将坏预警：元素名」，正文写明升幅（例如「未命中率连续两窗上升（12%→28%），标记将坏」）；同一页面成批条目一起将坏或陈旧，就是同一场改版风暴，按风暴卡一次处理即可。
5. **修订并回到稳态**：对点名条目点「编辑定位锚」对照真实页面修订，或点「退役」停用；修订被下次执行采纳后，健康度、将坏徽标与风暴卡自动回落，不需要人工清任何标记。
6. **核对自愈改了什么**：条目弹窗的「最近自愈」区按时间列出步骤与新旧定位表达式，可与执行报告里的徽标互相核对，确认每次自动换锚换到了哪里。

## 操作背后系统做了什么
- 自愈只认等效重定位：全部锚落空后，系统仅在能给出同 testid、同可访问名等强等价证据（或有视觉基线且比对相似度达到门槛）时才换锚并继续执行；断言目标类步骤（例如校验元素可见性的步骤）永不自动自愈，失败一律进入归因，防止自动换锚掩盖真实缺陷。
- 每次自愈留一行证据：新旧锚、视口、账本版本号、相似度随执行证据一起登记；批次报告的「自愈命中率」与元素库的「最近自愈」读的都是这同一份证据，两处数字可以互相核对。
- 健康账是纯统计零模型调用：系统按滚动 7 天窗口（可调）汇总每条档案的命中与落空，未命中率超过「注意」门槛（缺省 20%）亮黄、超过「高风险」门槛（缺省 50%）亮红；连续两个窗口上升且尚未全灭即标「将坏」并发通知。三个参数在系统设置里以 element.health.miss-warn、element.health.miss-bad、element.health.window-days 为名可修改，保存即生效，无需重启。
- 改版风暴按页面聚合：同一观察窗（缺省 24 小时，可调）内同一页面的陈旧标记累计达到门槛条数（缺省 3 条，可调）自动生成一张风暴卡，已陈旧与将坏分列并排、不混合计数；从未被执行触达的页面不产生任何告警。
- 视口分档：环境档案声明了 mobile、tablet、desktop 等视口档位时，执行按当前档位选用对应变体锚，不同屏幕尺寸各用各的锚集；未声明档位只用默认视口，不做猜测。
- 页面上「自愈命中率」「证据数」只有一套数字：全部来自执行证据的统计结果，看板不重复计算，也就不会出现两处读数不一致。

## 常见问题
- **自愈命中率高，是好事还是坏事？**——不能只看比率，要和「断言失配」数与近期证据趋势并读：比率稳定、证据数很少，属日常锚漂移，无需行动；证据数持续攀升，说明页面正在改版、自愈在替你兜底，应尽快到元素库修订锚。
- **带徽标的步骤为什么在用例里找不到？**——自愈只发生在执行时，证据随执行记录存放，用例文本不变；徽标出现在执行报告，明细在「最近自愈」区，用例脚本不会被自动改写。

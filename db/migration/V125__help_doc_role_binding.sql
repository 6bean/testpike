## 这一页能做什么
给用例声明「角色」，并为每个角色选择它在使用时怎么分配——每人一份、批内共享一份、几份轮换用、或干脆不绑定。声明之后，步骤里就能用「角色.字段」这样的写法取该角色自己的数据（比如各自登录后的令牌）；另外还有两种引用写法：跨用例共享的全局键、以及本次执行里上一步保存的变量。

## 怎么用
入口在侧边栏「用例资产 → 角色与绑定」页：
1. 选择项目和用例（该用例需已有可执行脚本），点「添加角色」。
2. 每张角色卡片填三样：角色名（支持中文，如「买家」）、绑定方式（四选一）、凭据来源（可先留空）。
   - **每虚拟用户一份**：每个使用者都自己登录、自己一套数据，互不干扰，适合「多用户各测各的」。
   - **批内共享一份**：整批任务只登录一次，所有使用者复用同一份凭据，省时间也避免被测系统被登录风暴限流。
   - **N 份轮转池**：准备 N 份账号轮换使用（如库存只有 3 个就填 3），用完自动排队。
   - **不绑定**：只做声明，暂不参与分配。
3. 卡片上会即时给出该角色的引用写法，点「复制」粘到步骤的「值」字段即可，全程不用手写任何配置文件。
4. 页面下方「引用变量三种写法」区可复制另外两种：`{{global.键}}`（跨用例共享的全局数据）和 `{{RUN.键}}`（本次执行中前一步保存的变量；和不加前缀的老写法完全等价，旧用例一字不改照常跑）。

普通功能用例不需要打开这一页——角色层只在本页出现，不声明就维持现状零变化。

## 操作背后系统做了什么
- 保存那一刻，服务端对角色声明做结构校验：名字不能撞系统保留前缀（如 RUN、global）、同用例内不能重名、轮转池份数必须是 1~9999 的整数；任何一条不过都会中文点名到具体角色，改完再存即可。
- 步骤里引用某角色字段时，校验同样要求该角色已在本页声明过——引用没声明的角色会被直接拒绝并点名，避免跑到一半才发现取不到数。
- 角色声明随脚本一起版本化管理：改坏了可以从脚本历史版本回退。

## 常见问题
- 保存提示「角色名撞了系统保留前缀」？——换名即可；ENV、DATA、PACK、VAR、SESSION、RUN、global 这七个词是引用语法的关键字。
- 老用例里没加前缀的变量引用要改吗？——不用。它们等价于「本次运行变量」写法，行为完全不变。
- 什么时候需要池？——当被测系统的数据或账号有限（如库存只有 N 件、只有 3 个测试账号），选「N 份轮转池」让任务排队取用而不是互相踩。

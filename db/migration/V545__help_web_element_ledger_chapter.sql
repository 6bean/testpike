'## 这一页能做什么
写用例时，网页步骤靠「页面里某个按钮、输入框怎么找到」的定位锚支撑。锚散落在各条用例文字里，页面一改版就逐条失效、逐条修补。这一页把定位锚集中登记成页面资产：一条档案对应一个页面元素，携带一组按顺序排列的定位锚与生命周期状态；页面改版时只在这一处修订，引用该元素的所有用例下次执行共同受益。入口：左侧菜单「页面元素账本」，顶栏切换项目决定本页展示哪一本账。解决的典型业务问题：改版后批量返工修用例、同一个控件在几十条用例里写法不一、无人说得清某个选择器现在还能不能命中。

## 总体流程
登记元素（候选态）→ 人工确认（已确认）→ 执行失手自动降档（待复核）→ 编辑定位锚修订或退役 → 命中与落空计数随执行累计 → 退役档案到期自动清理
账本沿候选、已确认、待复核、已退役四态推进；未确认的候选锚不会被执行引用；每一次状态推进都由人点按钮完成，系统不自动升级状态，只在执行证据表明锚打不中时降档提醒。

## 怎么用（按操作顺序）
1. 先在顶栏选择项目。未选项目时本页给出「还没有选择项目」提示，「登记元素」按钮不可用，点了也不会报错到别处。
2. 点「登记元素」：填写元素名与页面 URL，并配置一枚或多枚定位锚——类型支持 CSS 选择器、XPath、文本、占位符、alt、testid 等，列表中自上而下即尝试顺序；保存后这条档案处于「候选」状态。表单里写明「元素名与页面 URL 均为必填」。
3. 在列表找到这条记录，点行上「编辑定位锚」可增删锚、调整顺序；每次修改后系统把版本号加一，他人拿着旧版本的写入会被拒绝，不会出现悄悄覆盖。
4. 亲自验证锚确实能命中页面元素后，点行上「确认」把状态升为「已确认」——只有已确认的锚才会被用例执行引用。
5. 觉得某条锚暂时不可靠就点「待复核」；确定不再使用点「退役」，弹窗会点名这条档案的名字并说明退役后执行不再使用它。退役档案保留固定天数后自动清理（缺省 90 天，可在系统设置调整）。
6. 列表支持按「搜索元素名或页面键」即时过滤与「按状态筛选」；「命中质量」「命中 / 落空」「锚数」列展示这条档案被执行后的历史表现，翻页与每页条数照常可用。

## 操作背后系统做了什么
- 页面 URL 入库前折叠成规范页面键：/pets/123 这类具体路径与 /pets/{id} 模板路径归入同一页面，同一个元素不会因实例不同碎成多条档案；归一规则与接口契约的端点键规则共用一套定义。
- 同一项目、同一页面、同一元素名有唯一约束，重复登记会被拒绝并点名撞了哪条；跨视口尺寸需要不同锚时走变体字段按 mobile、tablet、desktop 分档存放，单视口资产不填即空。
- 「命中质量」不是模型自评分：执行上报命中与落空计数，服务端按真实结果重算，长期打不中的锚数值下滑并降档待复核，人因此看得出哪些锚在变坏。
- 状态机在服务端强制：候选可升已确认，已确认可转待复核，任一状态可退役；非法跳转被拒。每条写入携带乐观锁版本号（并发写只成一笔，另一笔被告知刷新重试），与用例编辑的 40901 版本冲突语义同一家族。
- 两条自动清理守护存量规模：已退役条目按「已退役条目保留天数」清理，长期未验证的候选条目按「候选待验证时长上限」自动转退役；两个天数都在系统设置热更（取值范围 1-3650），不重启即生效。


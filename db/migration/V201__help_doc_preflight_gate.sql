## 这一页能做什么
APP 自动化任务在「建任务、启动批次、机型矩阵扇出」那一刻，系统会先做一轮秒级健康检查：确认有合适的执行机、目标设备在线且没在冷却、要装的应用包已建档上传、引用的登录凭据能用。任何一项不满足，任务会被当场用一句拒绝并说明原因，而不是建到一半再失败——既不浪费执行机时间，也不用你去翻日志猜原因。
## 五道检查都查什么
1. **执行机在不在**：任务需要的自动化引擎（如 Mobilewright）至少要有一台在线的执行机声明支持。缺了会点名「需要什么引擎、当前在线几台、具备能力的几台」，指引你去执行机装好运行时并重新接入。
2. **设备在线吗**：任务指定了具体设备时，检查它的最近一次探活上报是否在允许空窗内（空窗时长可在系统配置调整，默认约五分钟），失联或被隔离的设备会点名提醒，先解除隔离或检查连线。
3. **设备凉快吗**：刚触发过热保护的设备在冷却窗口内暂缓派发（窗口时长可调，到期自动恢复），文案会告诉你距上次越温报警过了多久。
4. **应用包建档了吗**：步骤里要安装或核对版本的应用包，必须先在「被测应用包」里建档；要安装的还必须已上传安装包工件，否则跑起来只会空下载，这里提前拦下。
5. **凭据能解吗**：步骤引用的登录凭据会被逐一检查——存在、启用、密钥可正常解密才算通过，缺哪个点名哪个。
## 被拒了怎么办
- 拒单文案直接说明缺什么、去哪儿补：装执行机运行时、设备墙解禁、应用包建档上传、凭据管理页修复引用。
- 补好后重新发起即可：建任务被拒不留下任何半成品记录；整批启动被拒时本批任务整体回滚，重开批次就能继续。
- 任务已成功创建但暂时没有合适执行机时，会如实排队并给出预计等待，这属于正常现象，不是失败。
## 常见问题
- 为什么我在页面上点「执行」马上弹出红字而不是排队转圈？——这些属于上面五道检查的硬缺口，提前拒绝比让任务排队到超时再失败更快、更省机器。
- 检查会不会拖慢建任务？——五道都是读库与缓存的秒级判断，不做远程拨测，也不启动任何执行会话。
- 设备明明连着为什么被判离线？——探活由执行机周期性上报，若执行机本身离线或刚接入还没到第一个上报周期，会短暂判离线；稍后重试或检查执行机状态即可。

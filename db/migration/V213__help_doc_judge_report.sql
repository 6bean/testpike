## 这一页能做什么
AI 评测系统会按评分标准给被测产出逐条打分。这一页把一次评测的结果讲清楚：整体考得怎么样（评分卡）、哪几条最差最需要先看（样本卡片流）、两次评测相比谁进步了（运行对比）、花了多少 token 和钱（成本卡）、同一族标准的历史走势（趋势线）、以及各个被测对象各自的战绩（战绩卡）。
入口：左侧菜单「评测报告」；从通知里的评测结果也能一键直达对应报告。

## 怎么用（按操作顺序）
1. **选一次评测**：页面顶部填入评测运行编号后点「加载」；从通知直达时会自动带上编号，不用再填。
2. **看整体**：默认视图是评分卡——大数是这次评测的平均权威分，雷达图按评分标准各维度展开，旁边回显评测集、裁判、通过线等关键信息。
3. **看最差样本**：切到「样本卡片」视图，列表默认把得分最差的排在最前；勾选「只看低分」可过滤掉达标的。每张卡片能看到机器分与人审改判分两列并存——被人工复核改过的样本会带改判徽标。
4. **比两次运行**：切到「对比」视图，选两个评测运行（限同一套评测集、同一标准版本才有可比性），系统列出变好/变差/持平的样本，并给一句均值差是否显著的注脚。集不同或标准版本不同时会被直接拒绝并说明原因，不会给你看一个误导性的差值。
5. **算成本**：切到「成本」视图看这次评测实际消耗的 token 与折算金额。管理员没有设定每千 token 牌价时，金额列诚实留空并写明「未设牌价」——系统绝不编造一个数字给你。
6. **看走势**：切到「趋势」视图，选定评分标准族后看历次评测的均分折线；换标准会在曲线上留竖线锚，避免把不同尺子的分数连成一条误导性曲线。

## 操作背后系统做了什么
- 每条样本的「权威分」只有一个口径：人审改判过的以人工终分为准，没改过的以机器裁判分为准；报告页直接读这个合并结果，不做第二套计算，所以你在报告页、评审队列、准出判定里看到的是同一个分数。
- 通过线取的是评测运行快照里的值——之后管理员调整标准不会追溯改写历史报告的判定，老报告永远按当时的线解读。
- 对比视图的显著性注脚是程序化实算的（均值差做了双侧检验，和预设判定水平比较后给出「显著/不显著」措辞），不是拍脑袋文案；样本太少算不出时也会如实说明。
- 成本折算用的牌价是全局配置，管理员改完立即生效，下一次打开报告就是新价；token 实耗来自裁判管线的真实记账。
- 战绩卡按被测对象归组呈现通过率与均分；评测过程中被剔除的样本（裁判输出不合格等）会计数说明，不会混进分数里。

## 常见问题
- 为什么有的卡片有两个分数？——一个是机器裁判分，一个是人审改判后的终分；权威分取终分，两列并存方便对比人和机器的分歧。
- 为什么金额是空的？——牌价没设。请管理员在系统配置里设定每千 token 单价后即出现金额；未设时系统只报 token 用量。
- 两个运行明明差不多，为什么对比被拒？——对比要求同一评测集且同一标准版本，防止「换了考卷比分数」。报告会点名两边各自用的集和版本，便于确认。
- 低分筛选后卡片很少？——「只看低分」只过滤当前已加载的一页样本，先用分页/加深加载把样本拉全再看。
- 报告页打开提示「评测运行不存在」？——编号可能填错或该运行已被清理；从通知直达可保证编号有效。

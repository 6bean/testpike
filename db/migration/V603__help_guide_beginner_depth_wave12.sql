4. **过盲区清单**：行按「章节 / 需求点」分组，没挂章节的在「未分组」里；未覆盖是黄色行，行内没有的用例列为空格。
5. **直达处理**：黄色行格内点击提示「未覆盖：点击直达 AI 生成（需求点已预填）」——点进去在「AI 生成」页直接按该需求点生成，完成后回矩阵就能看到新用例进列；已覆盖的格子点击直达对应用例。想手工挂关系，就在用例的追溯信息里填上该需求点编号。没有需求点可挂时，先去「需求点管理」或「需求提取」把需求点建出来。
6. **回归确认**：回到本页签重新查看，该行应变为已覆盖、覆盖率同步回升；配合「变更分析」的端点缺口一起看，可以回答「契约变了我们漏测了什么」。

## 操作背后系统做了什么
- 联查现算：矩阵由需求点表与用例追溯关系实时联查计算，不落第二份统计数，因此不可能出现「矩阵和用例详情互相矛盾」。
- 关系语义：「已覆盖」= 该需求点存在至少一条在册用例的显式追溯关联；用例本身是否跑过、结果如何不改变覆盖标记，执行健康度看「执行统计」页签。
- 退役语义：需求点退役后，历史关联仍保留可查——需求点重新启用后覆盖矩阵与报表自动回算恢复；在架统计口径只算启用中的需求点。
- 删除跟随：用例删除后其追溯关系一并失效，矩阵当次打开即反映，不会残留旧格。

## 常见问题
- **明明有对应用例，矩阵却显示未覆盖？**——十有八九是追溯关系没登记：覆盖只认用例上显式填写的需求点编号，用例标题、备注里提到需求名不会被算上。打开该用例补填编号即可。
- **黄色行点进去，AI 生成页为什么已经带上了需求点？**——这是直达通道的设计：矩阵把该行需求点预填进生成表单，你补充描述后直接生成，新用例自动落回这张矩阵该行的列上，不用两头翻。
- **需求点太多找不到缺关联的那几个？**——先看顶部「未覆盖」数字，再用「章节筛选」「优先级筛选」逐段清零；也可以去「需求点管理」用状态筛选配合定位。
- **删掉的需求点去哪了？**——退役的需求点不再计入覆盖率，但它的历史关联可查，重新启用后覆盖自动回算恢复。

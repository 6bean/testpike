## 这一页能做什么
APP 用例在设备上跑到某一步失败、且系统判断「很可能是被测界面改了、不是产品真出了缺陷」时，会自动比对当时的现场画面与用例里那一步的定位锚点，给出一个候选修复（比如把点不到的按钮换成新的定位方式）。候选修复不会直接改动你的用例——它先进入「自愈建议单」等你批准，你采纳后系统才把它合入脚本落成新版本。

## 怎么用
入口：侧边栏「执行」组 →「自愈建议单」。
1. **看单**：选项目、选用例，列出该用例全部候选修复建议（新→旧）。每行展示失败步序号、原来的锚点、候选定位出处（视觉识别 / 无障碍树 / 定位缓存 / 人工标注）、候选动作与定位、比对理由，可再按「待批 / 已采纳 / 已驳回」筛选。
2. **采纳**：点「采纳」并确认后，系统把候选定位合入该步并真实生成脚本新版本，同时把这次「画面→定位」的对应关系回灌给 AI 定位样本库，越用越准。
3. **驳回**：点「驳回」仅留痕翻状态，用例脚本一个字都不动。
4. **开关**：采纳动作默认关闭。需要使用时请到「系统设置 → APP 自动化」把自愈采纳开关打开，改完即时生效不用重启；开关只拦「采纳」，看单与驳回随时可用。

## 操作背后系统做了什么
- 只有判定为「界面变更嫌疑」的失败才会进建议单；产品真缺陷、环境问题不会生成候选修复，避免把 bug 当成界面漂移「修掉」。
- 建议单的归属（哪个项目哪条用例）由系统按执行任务反查补全，前端传什么都不采信。
- 采纳瞬间会先核对脚本版本：如果你或同事在这条建议产生后改过脚本，本次落版会被拒绝并提示当前版本号，刷新拿到最新状态后重试即可——绝不覆盖别人的修改。
- 同一条建议被批过一次（采纳或驳回）就锁定，重复点击会收到「已被处理」提示，不会产生第二个新版本。


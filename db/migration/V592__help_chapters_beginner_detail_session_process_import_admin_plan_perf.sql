## 总体流程
登录步骤声明会话工件 → 首台机器执行登录并回传凭据 → 同批次其它机器领取任务时直接带上凭据 → 后续步骤按名字引用会话值免登录起跑 → 凭据失效时点名原因 → 重跑登录步骤自动恢复。

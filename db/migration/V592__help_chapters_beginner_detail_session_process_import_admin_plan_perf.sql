- 首台机器：登录成功后执行器把会话凭据回传平台，平台加密后按批次保管。
- 其它机器：领取任务时，平台把凭据随任务一并下发，步骤直接引用。
- 粘机模式：任务只派给持有这份会话的那台机器，其它机器排队等待。
- 失效恢复：被测系统拒绝旧会话时执行失败并给出原因，重登即恢复。

## 怎么用（按操作顺序）
1. **在登录步骤声明会话工件**：进入「设计用例 → 用例管理」打开用例，在登录类步骤的动作配置中补一段会话声明，格式为 "session": {"key": "login_token", "portability": "portable"}。key 填一个你自己起的名（如 login_token），表示登录成功后要把哪个令牌交出来传递；portability 填 portable 表示允许换机使用。

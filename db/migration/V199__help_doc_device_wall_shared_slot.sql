## 这一页能做什么
带你走一遍 APP 自动化测试的两块管理面：在「设备墙」登记与维护手机/模拟器设备、看清谁在占用哪台、什么时候释放；在「引擎中心」了解系统支持哪些自动化引擎与平台、按需调整展示名、优先级与上下架。全程界面点选，不用手写引擎配置。

## 怎么用（按操作顺序）
1. **登记设备**：左侧菜单进「设备墙」→ 选中项目 → 点「注册设备」，填名称、序列号、设备类型（模拟器 / ADB 远程 / USB 直连）；ADB 远程设备还要填接入地址（ip:port）。序列号是全局唯一的登记锚——同一台机器不管从哪个项目登记，都自动归入同一份档案，不会重复建档。登记后序列号不可改。
2. **看占用与排队**：列表的「占用情况」列直接显示哪台设备正被哪个执行器占用、预计什么时间释放；没被占用的显示「空闲」。点行上的「占用记录」可打开流水抽屉，看到这台设备完整的占用/归还历史，包括每次归还的原因（正常完成、超时回收、人工释放等）。
3. **隔离与解禁**：设备连续失联会被自动隔离（角标变红、显示「已隔离」），此时它不再参与排队；在设备上排查后点「解除隔离」即可重新参与排队。删除占用中的设备会被拒绝，并点名当前占用者。
4. **跨项目共享设备**：注册弹窗里勾选「共享位设备」（仅系统管理员可见）即可把设备登记为跨项目公共资产——不属于任何项目，所有项目都能在设备墙上看到它（带「跨项目共享」徽章）并直接借用。共享档案的增删改只有系统管理员能做；普通项目用户看到共享徽章行时没有编辑/删除按钮，但借用照常。归还后其他项目立刻可以占用，互斥规则与项目自有设备完全一致。
5. **看引擎目录**：左侧菜单进「引擎中心」，每张卡片是一个自动化引擎：支持哪些平台（Android/iOS/鸿蒙/小程序等）、什么设备形态、需要什么运行时与外部工具、动作能力清单、路由优先级和安装文档链接。引擎需要的命令行工具（如 ADB、节点运行时）需按安装文档自行安装，系统只负责调度与适配。
6. **管理引擎与平台**：有管理权限的账号可在卡片上点「管理」，修改展示名、路由优先级、安装文档链接，或把某引擎下架（停用）/恢复上架；平台目录同理可维护引导文案与上下架。下架的引擎对普通使用者立即不可选，新任务不再路由到它。

## 操作背后系统做了什么
- 项目自有设备按项目隔离：你只会看到自己有权限的项目的设备；共享位设备例外——它归属为空、全员可见，这是「借用不越权」的展示前提，写入闸（登记/编辑/删除）上提为系统管理员专属。
- 互斥占用由调度侧租约统一控制，一台设备同一时刻只会被一个批次拿走（共享位同样全局互斥，杜绝一台机被两个项目同时占用导致的双记账）；设备墙上的占用与流水是如实的展示投影。共享设备的每次占用流水记在借用方项目名下，谁在用、用多久、怎么归还的，追溯清晰。
- 设备在线状态与连续失联计数来自执行器的真实探活回写，页面不做猜测；预计释放时间就是当前占用的租约到期点，到期后系统自动回收并记一条「超时回收」流水。
- 引擎选择按「路由优先级」从小到大尝试，并要求执行器具备对应能力（装了什么工具、接了什么设备）；没有合格引擎时任务诚实排队等说明原因的提示，不会假装能跑。默认引擎可全局配置，配置了非法或已下架的引擎会自动回退到内置默认。
- 管理面的每次修改都会记审计（谁在什么时间改了什么），下架动作同时影响用户可选面与调度回退判定；查看跨项目共享设备的详情也会留访问审计，可追溯谁读过哪台公共机。

## 常见问题
- 别的项目已经登记过这台手机，我再登记会怎样？——序列号全局唯一，系统自动把两次登记归入同一份档案，不会重复建档；如果那台机被登记成了共享位，你的项目直接就能借它。
- 共享设备能被删除吗？——占用中的设备删除会被拒绝并点名占用者（与项目自有设备同律）；共享档案本身只有系统管理员能删。
- 为什么我在设备墙上看到一台标着「跨项目共享」的机器却没有编辑按钮？——共享档案的修改权在系统管理员；你所在项目可以直接借用它跑用例。
- 占用记录里的「预计释放」到了时间设备还显示占用？——回收由后台周期任务执行，最多滞后一个回收周期；期间新任务已不会派给它。
- 引擎卡片显示「暂无在线执行器」？——说明当前没有任何在线执行器上报，先检查执行机是否开机接入，与引擎本身无关。
- 为什么不能在这页改引擎支持的动作清单？——能力清单是引擎适配矩阵的数据源，随版本发布维护，界面只提供展示，防止改出调度与实际不符的假能力。

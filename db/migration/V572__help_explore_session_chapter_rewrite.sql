手工编写脚本只能覆盖你想到的路径，页面上没被测到的角落往往正是出问题的地方。智能探索让你用一句话描述目标，系统驱动真实浏览器或 App 自主访问页面、逐步操作并留下证据；探索完成后，你挑选跑通的步骤一键转为正式用例。入口：造数与资产 → 智能探索。列表页按项目展示每个探索会话的目标、起点、状态、步数/页面数与成本；点「详情」进入会话页查看步骤时间线、截图取证与探索报告。

## 总体流程
填写探索目标与起点 → 查看预估（tokens/成本/步数上限）→ 确认发起 → 后台执行，过程事件实时跟随 → 逐步复核证据（截图/思考/动作/结果）→ 勾选跑通步骤「转正式用例」进待评审队列。

## 怎么用（按操作顺序）
1. 在智能探索页点「新建探索」，选择起点形态：「网页（URL 起点）」或「App（移动形态）」。
2. 填写「探索目标」，用业务语言描述要验证什么，例如「遍历登录→下单→支付主流程，检查报错与空态」。网页形态填写起始 URL；App 形态选择或输入「被测应用」包名，并选择「目标环境」——只有开发/测试环境可选，生产环境禁止探索。
3. 可选：在「预置测试账号」中选择凭据保险箱里的账号引用，让探索以登录态进行。这里只传引用键名，口令全程加密、界面不回显。
4. 点「查看预估」，界面给出本次探索的 tokens、成本与步数上限估算，预算快照随会话固化。没有查看预估就无法「确认发起」——这是防止盲跑消耗成本的保护步骤。
5. 点「确认发起」后会话进入执行，页面顶部出现「过程进行中」徽标与事件计数；过程明细在尾窗子窗中实时滚动，向上滚动会暂停跟随并出现回到底部的提示，执行结束后列表自动刷新，不需要任何手动操作。
6. 执行中可对会话点「终止」（软终止，证据保留），结束后可点「删除」清理记录。
7. 在「步骤时间线」逐步查看：每步标注「跑通」或「未跑通」，点「取证」查看当时截图，展开「LLM 思考」「动作 JSON」「执行结果」核对决策依据。
8. 勾选要保留的跑通步骤，点「转正式用例」，确认后这些步骤落入待评审队列，与手工编写的用例走同一评审流程。

## 操作背后系统做了什么
- 发起后系统立即登记会话并转入后台执行，页面不等待结果；执行按「观察页面 → 模型决策下一步动作 → 执行器真实操作 → 回写结果与截图」的循环推进，直到目标达成、触达预算上限或被终止。
- 预算控制：发起时固化的预算快照是硬上限，超出后自动停止并标记「预算熔断」，已完成步骤与证据保留，可继续复核并转用例。
- 状态如实：会话状态分为「进行中 / 已完成 / 部分完成 / 预算熔断 / 已取消」五种，异常退出不会伪装成完成；失败步骤保留原始结果供分析。
- 安全边界：App 探索的目标环境白名单在后端校验，生产地址即使构造请求也会被拦截；转用例不绕过质量门，产物进入待评审队列由人决定采纳与否。
- 数据留痕：每一步的思考、动作、执行结果与截图逐条保存，成本按实际消耗累计，随时可回放核对。

## 常见问题
- **为什么点不了「确认发起」，提示「请先查看预估再确认发起」？** 预估是发起前的必经一步：先看 tokens/成本/步数上限估算，确认可以接受后再发起，避免不知情地消耗预算。

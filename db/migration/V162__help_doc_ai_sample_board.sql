## 操作背后系统做了什么
- 命中率由系统按样本表实算（确认数 ÷ 总数），页面只呈现、不重复计算，两边永远一个口径。
- 样本有两个来源：一是执行时的定位回灌，二是自愈建议单被人工采纳时，带坐标的候选定位会一并回灌——人批过的定位质量最高。
- 不同锚点之间互不串用：样本按「用例+步序+锚点」匹配复用，改了锚点就是另一条经验。
- 该用例暂无样本时统计卡显示 0，属诚实呈现，不代表功能故障。


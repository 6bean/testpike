## 这一页能做什么
APP 用例在用视觉识别、无障碍树等方式定位界面元素时，系统会把「画面长什么样、最终定位到哪」沉淀为样本存进样本库。本页按项目×用例展示这些样本的明细与「确认命中率」，帮你判断 AI 定位在这条用例上到底靠不靠谱。

## 怎么用
入口：侧边栏「执行」组 →「定位样本库」。
1. 选择项目、挑选用例，上方出现四张统计卡：样本总数、确认命中数、驳回样本数、确认命中率。
2. 下方表格列出该用例全部样本（新→旧）：步序、定位锚点、定位出处（视觉识别 / 无障碍树 / 定位缓存 / 人工标注）、复核结果、坐标、来源设备与采集时间。

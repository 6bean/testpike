## 这一页能做什么
登录态（浏览器会话/令牌）沉淀成账本条目，一次登录处处复用——用例执行、套件启动预检、项目探索与页面测绘、行内「立即测试」共用同一批条目，不必每个任务重新登录被测系统。入口：造数与资产 → 登录态账本。

## 怎么用
1. 采集或生成登录态后入账，标注归属项目与类型（令牌/浏览器会话快照/Cookie 集合）。
2. 用例与探索表单按名称选择登录态，运行时注入；口令等敏感材料始终留在凭据保险箱，账本只存会话产物。
3. 过期或被被测系统登出的条目会在使用时点名，重新采集或编辑续上。
4. 已登记的条目不是只读档案：每行有「编辑」，可改类型、引用键、站点范围、角色范围、备注，可在「附加会话头」区加行、删行、改值模板，也可以改名。「凭据值」留空保存=保留保险库里的原值不动；填了新值=用新值加密覆盖并重新解析到期时间。
5. 改名要留意：引用方按名称找到这条登录态，改名后请回到引用它的用例或探索表单重新选择。

## 这条登录态能用在哪里
- 用例与脚本执行：浏览器自动化用例声明使用某个登录态（执行前由服务端装配注入，脚本里不落明文）。
- 套件/批次启动预检：批次引用的登录态过期或停用时，启动前就点名拦下，不跑一半才失败。
- 项目探索与页面测绘：选择登录态后以业务身份打开页面采集元素，避免把登录页当成业务页。
- 站点监控：监控目标的登录探测可绑定登录态，探测请求自动携带账本里的会话，不必单独配一套口令。
- 行内「立即测试」：拿账本里的会话材料向目标地址重放一次真实请求，验证条目还能不能用。
- 不在此列的通道说清楚：接口测试请求的认证走「凭据保险库」引用与变量（{{CRED:键}} 语法），那一路不消费登录态行。

## 操作背后系统做了什么
编辑保存落在同一行（编号不变），保存前服务端校验：名称在项目内唯一（撞名会被点名）、类型只能是三种之一、附加会话头的头名不能与该类型自带的主请求头同名、清单内头名不得重复、引用的凭据必须已在「凭据保险库」建档；填了凭据值时还会校验「值与类型相配」——浏览器类型（Cookie 集合/会话快照）要求值是 Cookie 条目数组、Playwright 快照或 k=v 原文之一，粘成一段令牌文本会被当场点名（改类型为 token 或按 Cookie 形态重新采集），不会等到「立即测试」才报错。只要更换了登录材料（类型、引用键、凭据值、附加会话头任一变化），「最近核验」时刻即清空，需要重新点一次「立即测试」确认；只改账号说明、备注这类信息不会清空核验时刻；没有任何改动的保存不产生写入。

## 立即测试
列表每行有「立即测试」：用账本里的会话材料向目标源重放一次真实请求
（留空=第一条登记作用源，也可手动指定受保护地址）。过程流逐行给出
探测目标、构造请求（会话值恒打码）、HTTP 应答与判定：
2xx=会话仍在，重定向到登录页或 401/403=需要重新采集。有效判定自动盖「上次验证」时刻。
- 报「会话材料无法解析」？说明保存的内容形态和登录类型不匹配（例如把一段令牌粘进了
  Cookie 类型）。按提示给出的改法操作即可：改类型为 token（凭据值留空保存，不会弄丢
  现值），或按 Cookie 形态重新采集；不必反复重登被测系统。

## 过程里的请求与返回怎么看
点「立即测试」后，页面下方打开「过程详情（实时）」抽屉跟随进度滚动；每一步点「展开」可看到完整交换数据：请求行（方法、地址）、请求头、状态码、响应头（含 Set-Cookie）、响应体。
- 会话值、令牌等敏感内容以打码形式显示（前 8 个字符 +「总长度 N」）；点「显示明文」当场取回真实值，每次读取都会留一条审计记录。「复制原文」按钮只复制打码文本，明文不提供一键复制。
- 内容超出显示上限时末尾出现「共 N 字节，展开全文」，点开后分页续读，点「继续加载」直到「已读取全部」。两个上限可在系统设置中调整（参数 ui.tail.detail-max，默认 16384 字符；session.probe.body-max-bytes，默认 65536 字节；保存即生效）。
- 向上滚动会暂停跟随（显示「已暂停跟随，正在回看历史」），点「跳到最新」恢复；「显示明文」若提示「明文读取失败，请重新执行一次测试后再试」，重新执行一次测试即可。
- 常见问题：没等到响应体那一行？探测失败或目标无应答时对应行仍会落账，判定行写明原因；打码值看着像被截断？打码只是显示形态，重放与测试用的都是完整值。


## 一个身份带多把钥匙（附加会话头）
有的站点一个已登录会话要同时带两把钥匙：例如主令牌走 Authorization 头，另一把 API Key 走自定义头。登记登录态时，「登录类型」下方的「附加会话头」区可以把后一类头一并登记：每行选择本项目凭据保险库中已建档的凭据，填写头名称（如 X-API-KEY），可选填值前缀模板（如 Bearer 加引用占位符）。执行与「立即测试」时由服务端在发送前一刻组装，效果与不带附加头的登录态完全一致。
- 为什么界面上看不到口令值？附加会话头只存引用不存值：实存的密文留在凭据保险库，重放时即时装配、全程打码展示，需要核对时按既有权限单独解密查看并留审计——登录态这一行被分享或导出也带不走任何密钥。
- 能带几条？出厂上限 8 条（可配置调高），超出会被拒绝并提示当前上限；同一凭据在同一登录态里不能重复挂两次，也不能与登录类型自带的主请求头同名，保存时会被点名拒绝并说明怎么改。
- 想调整附加会话头？直接点该行的「编辑」，在「附加会话头」区加行、删行、改头名或值模板后保存即可整体替换；删光所有行=取消全部附加头。
- 同名重新采集会更新登录材料，但不会清掉你登记的附加会话头。

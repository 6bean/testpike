## 操作背后系统做了什么
- 明文的可见窗口只有一次：完整值只在创建响应里返回，服务端只存可校验的凭据材料，列表接口只回指纹前若干位。因此「忘记明文」不是显示问题，无法找回，只能重建。
- 每一次调用都做双重校验：权限范围决定能不能调这个能力，项目范围决定能不能碰这个项目的数据；任一条不满足，调用被拒绝并回说当前令牌的范围，方便接入方定位。
- 状态是计算出来的：过了「过期时间」的令牌不再可用；被吊销的令牌立即失效，不影响同一属主的其他令牌。
- 角色的权限覆写保存后，令牌侧最迟在一次刷新后生效——也就是接入方无需重发令牌，权限变更会随令牌刷新落到调用判定上。
- 签发、使用、吊销全程留审计，可按指纹追溯到具体接入方与时间点。


## 这一页能做什么
日常验证后端接口（登录拿令牌、下单、查询返回对不对）不用开着命令行工具一条条敲。这一页把 HTTP 请求像浏览器收藏夹一样收进「集合」，按业务分组管理；单条可以随时发起看结果，多条能成批跑，跑完的响应自动留档，方便比对「这次和上次返回一样吗」。入口：左侧菜单「执行测试 → 接口测试」。

## 怎么用（按操作顺序）
1. **建集合**：先给一组接口建个集合（比如「订单服务冒烟」），集合就是收藏夹，权限跟着项目走。
2. **存请求**：在集合里新建请求——选好方法（GET/POST 等）、填地址、按需加请求头和参数，保存后可随时编辑。地址里的固定前缀（域名、鉴权头）可以配成集合变量，切测试环境和预发环境只改一处。
3. **单发看结果**：点「发送」当场看状态码、耗时和响应体；断言写在请求上（比如「状态码必须是 200」「返回里必须有订单号」），不满足会直接标红。
4. **成批跑**：勾选集合里的多条请求一次性发起，逐条给出通过/失败与耗时，结果页可以回看每条的完整响应。
5. **结果留档**：每次跑批都会留下一份记录，点历史批次就能看到上一次和这一次的差别，回归对比不用手动截图。

## 操作背后系统做了什么
- 请求真正发出前，服务端会核对你对这个集合所属项目的访问权限；别人的集合你既看不到也发不了，杜绝跨项目误发。
- 批量执行由执行侧统一排队：请求按顺序或配置的并发发出，单条超时不影响整批，失败条会带上完整响应体落库，方便点开看现场。
- 变量替换发生在发送前的最后一刻，所以同一份请求配置在不同环境下不用改动内容，只换变量值。

## 常见问题
- 为什么我的请求发送后一直转圈？——多半是目标地址本机不可达或服务未启动；先看地址和端口对不对，再用浏览器或命令行验证同一个地址通不通。
- 断言失败了但接口其实没报错？——断言按你写的规则判，规则本身写错（比如状态码写成字符串比较）也会红；点开该条的响应详情核对返回值形状再改断言。
- 历史留档会占空间吗？——留档按批次滚动保存，只存响应文本与关键指标，单条体积很小；需要长期对外交付的结果请用报告的导出功能。

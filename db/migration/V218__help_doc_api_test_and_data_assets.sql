## 这一组页面能做什么
测试最怕「没有合适的数据」和「每次回归都手动挑用例」。这一组页面把支撑性资产集中管理：批量造测试数据的配方、常跑用例打包成的回归集、用例分类用的标签字典、帮你找漏测角落的智能探索，以及按业务角色画像造数造场景的角色卡。入口：左侧菜单「造数与资产」。

## 各页一句话（按需直达）
- **造数工厂**：把「怎么造一条合格数据」写成配方（字段规则、取值范围、关联关系），一键批量生成，产物进数据池供用例引用——不用手写一百条假订单。
- **回归集**：常跑的那批用例打包成套（比如「核心链路冒烟 20 条」），建批次时直接挂整套，换人接手也不用重新挑用例。
- **用例标签**：维护按模块、优先级等维度的分类字典；标签打得准，筛选和统计才准。
- **智能探索**：让系统根据已有用例和页面结构给出「还没测到的角落」建议，补测有方向。
- **角色卡**：按业务角色（普通用户/店长/审核员……）画像生成配套的账号数据与操作场景，权限类用例造数不再拍脑袋。

## 操作背后系统做了什么
- 造数配方按字段规则批量生成时逐条校验，不合格的当场剔除并在结果里点名第几条哪个字段违例，不会把脏数据混进池子。

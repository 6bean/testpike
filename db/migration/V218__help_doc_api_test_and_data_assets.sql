## 常见问题
- 造出来的数据能删吗？——数据池里未被人引用的产物可以直接清；已被用例引用的会提示占用方，防止删一半把用例跑挂。
- 回归集和测试计划有什么区别？——回归集是「这批用例」本身，可反复挂进不同批次；计划是「一次要完成的测试活动」，会带时间窗和责任安排。
- 标签和文件夹分类选哪个？——一条用例常同时属于多个维度（模块×优先级×冒烟范围），标签可以多打，文件夹只能待一处——推荐用标签做横切，文件夹管归属。

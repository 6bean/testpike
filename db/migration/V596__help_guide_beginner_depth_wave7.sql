- 紫色「AI 兜底应答」标 = 规则没有对上，系统按开关授权动用了一次大模型生成的答案。这是花了 token 的付费兜底，永远单独标注，不会伪装成规则命中。
- 灰色「真实服务转发」标 = 开着录音盒且绑定了真实目标时，请求被转发给了真实依赖，这条应答来自真实服务本身，仿真规则没有参与。
- 老记录或普通落空行没有来源标 = 该请求没有可归属的应答来源，页面不补造标签。


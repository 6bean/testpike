- 命中账本走异步攒批写入：在途缓冲条数、是否已降级落盘、溢出丢弃条数都直接写明。丢弃只意味着账本有缺口，不意味着请求失败。
- 应答来源由数据面在给出答案的那一刻写下，随账本一起落库；页面只呈现落库的值，事后不改写、不补标。
- 请求快照在进入页面之前就已由管道脱敏，页面上不存在「解开看原文」的路径。


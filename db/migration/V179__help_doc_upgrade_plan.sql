## 这一页能做什么
升级计划回答「这批引擎节点怎么安全地升上去」。管理员在升级中心里发起一个计划：先圈定升级范围，系统现场算出影响面让你二次确认，然后按计划灰度派发升级命令——先金丝雀验证、再分批滚动，中途出问题可以暂停、继续或终止，触发自动刹车还会回滚。

## 怎么用
入口：左侧菜单「执行中心 → 升级中心 → 升级计划」页签，走三步：
1. 选范围：勾选要升级的引擎节点分组与目标版本；「灰度批次」留空时默认首批只发一台（金丝雀），确认无误再放量。
2. 看影响面：第二步实时呈现本次计划覆盖多少节点、分几批、涉及哪些部件版本变更，数字是现场计算的，核对后点确认执行，计划即进入预览态落库。
3. 盯进度：第三步是计划进度链——每个节点一行状态（待执行/执行中/成功/失败/跳过），可以按计划暂停、继续或终止。
版本全景页签用三色徽章纵览所有集群部件的当前版本分布，鼠标悬停徽章可看不达标的原因。

## 操作背后系统做了什么
- 影响面数字与落库步清单是同一次现算的同一套账（同一套算法现算），不存在预览一套、执行另一套两本账。
- 派发按波次推进：金丝雀批次全部成功才放开下一批；金丝雀失败率超阈值自动刹车——停止派发并把金丝雀机回滚到原版本，同时给带原因的告警；批量阶段失败（金丝雀已验证通过）只刹车不回滚，提示核对回执后重建剩余计划。
- 预览态的计划尚未派发，不提供终止（没有可停的东西）；只有执行中或已暂停的计划才有暂停/终止按钮，按钮按状态显隐，不会出现点了没反应的假操作。
- 每次状态变化都留痕在计划进度链上，事后可以逐节点对账。

## 常见问题
- 灰度批次留空会发生什么？——默认首批只升一台做金丝雀验证，这是推荐姿势，不是遗漏。
- 计划中途终止了，已升级的节点要手动回退吗？——终止=当前批跑完后停止派发，已升级成功的节点保持新版本不动（只有自动刹车触发的金丝雀机回滚是系统自做）；剩余未升级节点核对后重建计划继续即可。
- 为什么我看不到「执行」按钮？——升级计划的操作权受权限控制，没有相应权限的角色只能查看不能发起。

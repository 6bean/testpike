「保存角色声明」把角色、绑定方式、数据源、别名四件事作为一个整体写入，执行开始时服务端对其做快照，运行中途声明再变也不影响正在跑的任务。领数规则在每次请求解析时生效：系统沿「角色 → 绑定方式 → 别名 → 具体值」链条替换占位——「每虚拟用户一份」按虚拟用户序号从池里独占分配，用户之间互不串数据；「N 份轮转池」按序号对 N 取轮转位复用；「批内共享一份」全体用同一条。池中可用数据不够分时（例如选了每虚拟用户一份却只有 30 条数据要跑 100 并发），不会默默复用同一份造成脏互踩，而是在派发前就失败并点名缺数的角色与别名，指引你回造数工厂补足。「不绑定」的角色不参与分配，仅用于权限语义与统计归组。引用计数在服务端维护：数据池回收、别名改名都会检查是否被角色声明引用，有引用的改动会先点名影响面。

## 常见问题

- **「角色与变量引用」的帮助章讲过别名，和这里什么关系？** 变量引用讲「值从哪来、怎么在用例里写」；角色卡讲「谁在执行、领哪一份数据」。别名是两边的接头：角色声明里建组，用例里引用组名。
- **跑批报「数据不足」类失败，改哪里？** 先看绑定的数据池余量：到「造数工厂 → 数据池」按环境和数据类型查未使用条数，不够就再执行一次造数脚本补充；账号确实有限，把绑定方式从「每虚拟用户一份」改成「N 份轮转池」并把 N 调到余量以内。
- **改了角色的绑定方式，已经写好的用例要跟着改吗？** 不用。用例只引用角色名与别名，绑定方式改变只影响执行时领数的动作，下次执行自动生效（进行中的任务按开始时的快照跑完）。
- **「不绑定」的角色有什么用？** 表达权限语义与报告归组：例如「审核员」只出现在断言「该角色看不到某按钮」的用例里，不需要领账号数据。
- **多个项目都要同一套买家/卖家画像怎么办？** 逐个项目重复维护成本高，建议把配套数据做成系统级资产进「资产池」，各项目引用后再各自绑角色，数据源维护只剩一处。

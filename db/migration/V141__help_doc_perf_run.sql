## 这一页能做什么
带你走一遍性能压测的完整操作：在「压测工作台」建场景、发起压测、盯实时曲线、看终态报告、和上一次运行做版本对比。全程界面点选，不用写任何压测脚本或配置文件。

## 怎么用（按操作顺序）
1. **建场景**：左侧菜单进「压测工作台」→ 选中项目 → 点「新建场景」，跟着五步向导填：压什么（从 API 测试资产里挑请求）、多大力度（并发与压力形态：恒定/爬坡/脉冲）、跑多久、判定线（成功率、响应时间上限等阈值）、安全档（隔离模式与驱动上限）。保存前界面会给出预检红绿灯，哪项不过会可读点名。
2. **发起压测**：场景行上点「起压」直达运行页；或在「运行历史」抽屉里发起。生产环境压测需要先过三道门（管理员总开关、项目白名单、审批单），任何一道没过按钮会告诉你缺哪一步、找谁办。
3. **盯曲线**：运行页每两秒自动刷新，三条曲线分别是每秒请求数、P95 响应时间、错误率。错误率触到你设定的熔断线会自动停压，页面顶部出现说明原因的横幅说明为什么停、下一步能干什么（重跑或调整场景）。中途想停就点「停压」，确认后会保留已采数据进报告。
4. **看报告**：运行进入终态后页面自动挂载报告区——八项指标卡（采样秒数、平均/峰值 RPS、P95、平均错误率、熔断与门禁结论等），每项带红绿灯；结论下方列出触线的门禁项。点「发送卡片」可把报告摘要推给项目成员，界面会回执实际送达人数。
5. **版本对比**：报告区选另一终态运行做对比，得到两条 RPS 叠加曲线与逐秒差值表，用于回答「这次改动比上次快还是慢」。

## 操作背后系统做了什么
- 起压请求先过安全闸核对（开关/白名单/审批/禁入时段），全部通过才下发压测任务；压测引擎与业务执行链隔离，影子流量或独立命名空间按场景档案自动选择，不会污染生产数据。
- 曲线数据按秒采样入库，页面轮询只读最新帧；熔断判定在引擎侧实时执行，触线立即停压并记录原因，报告里的结论以运行时钉住的阈值快照为准（事后改场景不影响已跑完的报告）。
- 停压、超时、熔断三种结束方式都保留完整已采数据，报告口径一致。


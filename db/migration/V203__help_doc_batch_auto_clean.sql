## 这一页能做什么
移动端测试最常见的坑不是用例写错，而是设备不干净：上一批留下的登录态、缓存数据、残留安装会污染下一批结果，造成「同一用例有时过有时不过」。开启「跑批后自动清机」后，批次跑完（成功或部分失败结束）系统会自动把这批用过的设备恢复初始态，下一批从干净状态起跑。

## 怎么开
- **建批时勾选**：新建批次表单里的「跑批后自动清机」开关，默认关；
- **草稿批随时改**：批次详情页的元信息区可直接切换（仅草稿态可改，启动后只读回显）；
- **模板带默认值**：开启清机的批次保存为模板时，模板记住这个开关；按模板建批时自动带上，仍可逐批改。

## 系统实际清什么
只清「与本批有关」的东西，不碰设备上其他应用：
1. **清数据**：对本批脚本里显式声明过包名的被测应用，清除其本地数据（相当于恢复出厂的应用数据）；
2. **卸载**：卸载本批安装过的应用包；
3. **只清本批占用的设备**：按这批任务实际占用过的设备逐一恢复，其他设备零动作。

## 失败会影响批次结果吗
不会。清机是批次结束之后的尽力而为动作：设备离线、没有可用执行机、派发被拒等情况只发一条可读站内信留痕，批次本身的成功/失败结论完全不受影响。你也可以随时在批次列表重跑失败集，不受清机痕迹干扰。


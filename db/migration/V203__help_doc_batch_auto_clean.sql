- 为什么默认是关的？——防止误清被测方设备上的珍贵数据（如手工造的账号态）。确认为测试专用机再开。
- 纯网页用例批次开了会怎样？——只有包含 APP 自动化用例的批次才会实际清机，网页批零动作。
- 批次里只有个别用例需要清？——批级开关关时，勾选了用例级清机旗标的用例，其脚本声明的包仍会纳入清机集。

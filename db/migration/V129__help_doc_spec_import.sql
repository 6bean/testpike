## 这一页能做什么
把接口文档（OpenAPI 3 的 JSON/YAML）一键批量变成 API 测试请求资产：解析出接口清单后先给你预览，勾选哪些写入哪些，确认后才落库——系统永远不会替你自动写入。

## 怎么用（三步，全程不用写配置文件）
入口在「API 测试」页工具条的「从接口文档导入」按钮：
1. **选文档**：三种来源任选——挑项目里已上传过的契约、直接粘贴文档全文、或把 .json/.yaml 文件拖进来。解析是确定性规则，零费用，界面会如实告诉你「检测到 N 个接口」。
2. **预览勾选**：接口按文档标签自动分组，卡片流列出方法/路径/标题，可搜索、可展开看参数数量与默认断言。每条接口默认带好三行断言（成功状态码 + 响应结构 + 耗时上限）；标记为「存疑」的低置信条目默认不勾，人工确认后再勾。
3. **写入**：点「写入 N 个接口」后系统在同一笔事务里按标签自动建集合层级（如「宠物/查询」）并生成请求；之前导入过的接口会自动跳过不重复。完成页如实报「新建多少、跳过多少」，回到列表即可继续调试。

## 操作背后系统做了什么
- 解析只读结构不花钱：文档先做版本留痕（同内容重复上传会被点名拒收，防重复版本），再按规则映射成请求草稿——参数、请求体、凭据都只登记引用，凭据明文一律不落。
- 勾选写入走单点批量事务：一条链路完成全部集合与请求创建，中途失败整体回滚，不会留下半截数据。
- 幂等按接口键（方法+路径）判定：同一份文档改几个接口重新导入，只有新勾的会写入，老的不产生重复。

## 常见问题
- 导入的接口能变成测试用例吗？——能。请求资产继续调试通过后，可在 AI 生成页按接口生成用例。
- 文档里有几百个接口会全导吗？——默认全列但不自动写；按分组搜索、只勾需要的部分即可。
- 重新导入同一份文档会产生重复请求吗？——不会，已写过的接口自动跳过。

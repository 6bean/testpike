- **为什么置信度偏低？** 需求描述太笼统或验收标准与步骤对不上。回到需求点补充验收标准与业务上下文，重新生成。
- **为什么批量提交被拒绝？** 超出单批数量上限。拆分提交，或请管理员在「系统管理 → 系统配置」调整上限。
- **为什么生成的写法不像我们团队的？** 项目里可参照的优秀用例太少。先在历史用例里标记几条代表性的，再生成。
- **为什么生成完了矩阵还是黄色？** 只有评审通过的用例才计入覆盖，草稿和待评审不算。先到「评审工作台」把用例拍板，再回来看矩阵。

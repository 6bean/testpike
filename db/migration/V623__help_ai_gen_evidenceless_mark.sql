## 这一页能做什么
手写测试用例最费时的两件事：一是把需求读薄、逐条落成用例；二是用例攒多之后说不清哪些需求已覆盖、哪些漏测。这一域解决整条链——先把需求管成结构化的「需求点」，再让 AI 按需求点一键起草用例，人只做评审拍板，最后用覆盖矩阵交代每个需求的覆盖状况。需求→用例→评审→覆盖全程不离开平台，不再靠线下表格对账。

入口：左侧菜单「需求与生成」——「需求点管理」管生成输入，「用例管理」发起生成与处置结果，「覆盖矩阵」看漏测；生成完成后用例进「评审工作台」拍板。所有数据切片跟随顶栏所选项目。

## 总体流程
上传文档或手工维护需求点 → 选中需求点发起生成 → AI 起草结构化用例 → 系统逐项自检 → 提交评审 → 评审通过拍板 → 覆盖矩阵计入。
- 需求点管理：生成的输入源头，一条需求点对应可验收的标准，文越实、生成越准。
- 发起生成：单条走一键生成，批量多选一起提交且默认按场景枚举展开多条用例，页面实时显示进度。
- AI 起草：产出含测试目标、前置条件、操作步骤、预期结果、优先级、置信度的完整用例。
- 系统自检：字段完整性、步骤编号、验收标准比对逐项过关，不合格自动重生成。
- 评审拍板：评审人决定通过、退回或修改，通过后才是正式用例。
- 覆盖矩阵：需求点×用例的覆盖视图，黄色行代表漏测，可一键补生成。

## 怎么用（按操作顺序）
1. **备好需求点**：进「需求与生成 → 需求点管理」手工补录，或走文档提取——上传需求文档后系统自动提取需求点供你确认。每条需求点尽量带上可验证的验收标准，这是生成质量的第一决定因素。
2. **发起单条生成**：在「用例管理」选中目标需求点发起 AI 起草。发起前先确认顶栏已选中项目；生成结果自带置信度与端属性（web / mobile / pos），一眼看出这条用例的可信度和将要在哪端执行。
3. **批量生成（默认一个需求点出多条用例）**：多选目标需求点后直接提交，系统会先按每个需求点自动枚举主流程、等价类、反例、边界、状态组合五类场景并默认全选，再按展开后的条数提交；批量动作区常驻这句说明，成本确认弹窗里显示的条数就是展开后的真实提交数。想先删减，点「场景预览」圈选要生成的场景再提交即可。页面实时显示进度 x/N；个别失败只重试失败项，不用整批重跑；单批上限由管理员在系统配置设置，超出会被点名提示拆分。
4. **检查与调整草稿**：打出生成的用例逐条对需求点核对——步骤是否可执行、预期是否可验证；优先级由系统自动建议 P0/P1/P2，评审时可改；新建时与库内高度相似的用例会提前提示，防止重复入库。步骤里的页面地址、元素定位或期望值，如果没有探查记录或接口契约作依据，草稿会把该步骤标上「需人工精化」——见到标注先核那一步：在目标环境实际探查一次、补全接口契约，或手工改成已核实的值。
5. **评审拍板**：用例送「评审工作台」，评审人通过、退回或修改后通过。只有通过评审的用例才计入覆盖。
6. **补漏与复用**：「覆盖矩阵」中的黄色行即未覆盖的需求点，一键发起补充生成，完成后直接跳转评审；相似用例可克隆——同项目变体或跨项目复制，均保留来源标注。

## 操作背后系统做了什么
- 批量提交的自动枚举与「场景预览」用的是同一套五类场景枚举逻辑，先圈选与不圈选只是先后顺序不同，场景口径一致；每条需求的场景数受单需求点上限与优先级裁剪规则约束，不会无限扩张。自动枚举临时不可用时，本批会按每个需求点一条继续提交，并在成本确认弹窗里点名原因，不会不明不白地少出用例。
- 生成结果先过机器检查：字段完整性、步骤编号连续、预期结果非空，并逐条比对需求点的验收标准——每条标准都要有用例步骤承接。任何一项不合格自动重生成（最多两次），仍不合格也会如实标出交人工评审，不会静默放行不合格草稿。
- 生成措辞会参照团队历史用例与你标记的「优秀用例」对齐风格：标记样本越多，产出越贴近你们的写法；项目里没有参照样本时，产出走通用风格。
- 置信度是系统对「草稿与需求点贴合程度」的自我评估，用来提示你优先人工核哪几条，不替代评审结论。
- 落库前草稿还会做一次依据核对：Web 步骤用到的元素定位要能在探查记录里找到、接口步骤的地址与期望值要能在接口契约里对上。查无依据的具体值会逐处标注「需人工精化」，并记录在该任务的处理过程里；带标注的用例置信度不会停在最高档，系统会把数值下调（库里已是更低档时保持不变，重复保存也不会二次改动）。如果其他人在此刻抢先编辑了这条用例，下调会被取消并在处理过程里点名原因，请你评审时人工复核标注步骤。这项核对由参数 ai.gen.no-truth-honest-mark.enabled 控制，默认开，可在「系统管理 → 系统配置」调整，修改即时生效。
- 覆盖矩阵只统计评审通过的用例，草稿与待评审不计入——矩阵黄色不代表没人写，可能只是没拍板。
- 用例的生成、修改都按版本链留痕，评审前后的差异可以回查。

## 常见问题
- **为什么批量提交一下子多出这么多用例？** 这是默认形态：每个需求点先自动枚举五类场景、默认全选展开。不想全要，就在提交前先点「场景预览」删减；也可以请管理员在「系统管理 → 系统配置」把参数 ai.gen.batch.auto-enumerate.enabled 关闭，批量提交恢复为每个需求点一条。

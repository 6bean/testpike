## 这一页能做什么
在用例的脚本编辑器里，用一句中文描述（例如「打开购物车页面并点击结算按钮」），系统会按该用例所选执行引擎的能力，自动拆解成一串 APP 操作步骤草稿。你勾选确认后并入步骤序列，仍可逐条修改字段，最后统一保存。

## 怎么用
入口：用例详情 → 「脚本」区 → 「树编辑」→ 工具条「一句话生成步骤」。
1. 前提：用例的自动化目标已选「移动 App」或「小程序」，且已选好执行引擎（没选引擎时按钮旁有说明原因的提示）。
2. 输入一句中文操作描述，点「生成步骤」。
3. 草稿列表默认全选，可按步勾选/取消；「全选」一键切换。
4. 点「并入 N 步」把勾选的步骤插入编辑器（插入位置=当前选中步骤之后，未选中=列表末尾）。
5. 并入只是暂存：检查/调整字段后点「保存」才写入用例；并入本身可撤销。

## 操作背后系统做了什么
- 生成前先按引擎能力裁剪：该引擎做不到的动作会被直接去掉，只回可用的步骤；模型应答里出现能力之外的动作时整条拒绝，不会混进草稿。
- 描述为空、引擎未选、目标不是 App/小程序等情况都会被逐条拒绝并说明原因，提示写清缺了什么。
- 这个功能默认关闭：开关未开启时会弹出提示卡并给出「去系统设置」直达入口，由管理员在「系统设置 → APP 自动化」开启后重试。
- 生成不写任何数据：结果只是草稿，持久化走脚本编辑器既有的版本保护链（他人已改会提示冲突，绝不静默覆盖）。

## 常见问题
- 生成的步骤为空？——描述可能超出了该引擎能力范围，换个说法或改用支持该动作的引擎。
- 并错了想撤回？——用编辑器「撤销」即可，草稿并入不落库。
- 按钮是灰的？——先在用例编辑区选好执行引擎；切回「网页」目标时此入口不出现。

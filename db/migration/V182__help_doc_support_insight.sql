- 顾问的回答基于该项目的真实画像（用例量、常用引擎、近期稳定性）与版本变更清单交叉得出，不是模板话术；开关关闭或供应商不可用时，页面会明确告诉你「现在问不了」以及为什么，而不是转圈或空结果。
- 排窗的账本口径：与正在跑的批次时间有冲突的窗口会被红线拦下直接拒答推荐，宁可不推也不推一个撞车的窗口。

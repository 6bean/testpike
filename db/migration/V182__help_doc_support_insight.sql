## 这一页能做什么
引擎中心每张引擎卡上的「支持度」按钮，回答的是「我选了某个项目之后，这个项目的自动化用例在各引擎上跑得怎么样」。它把两条独立的账放在一起看：一条是版本账（该引擎的推荐版本相对当前安装版本是新是旧、要不要升），一条是健康账（最近真实执行的成功率、失败都错在哪类）。两条账各自给三色结论（绿=放心用 / 黄=有信号要看一眼 / 红=建议处理），互不掺水——版本很新不代表跑得好，跑得好也不代表该升的没升。

## 怎么用
入口：左侧菜单「执行中心 → 引擎中心」，先在页面顶部选好项目，再点任一引擎卡上的「支持度」。抽屉里每种引擎一行：两个维度的徽章、一句易读结论、样本数与成功率，行下按平台展开分组明细（该平台跑了多少样本、成功率、错误类型分布、定位失败分布）。

## 操作背后系统做了什么
- 每条结论都是系统现场算出来的：拿该项目最近的真实执行流水，按引擎×平台分组算成功率，再对照推荐版本判定谱给结论。前端只呈现，不另算一套，页面上看到的数字和后台对账是同一套账。
- 样本太少时结论会诚实降级：没有足够执行样本的引擎会明确标注「样本不足，暂不判健康」，而不是拿一两次的偶然结果下结论。

## 这一页能做什么
升级中心的「升级洞察」页签管三件事：升级前，选一个项目和目标版本点「问顾问」，系统给你一份该版本对这个项目的风险与建议；升级排期，系统按批次占用情况算出未来哪些时间窗空闲、推荐哪个窗口放金丝雀；升级后，把「升完通过率骤降」的节点归因列出来，帮你判断是不是这次升级惹的祸。

## 怎么用
入口：左侧菜单「执行中心 → 升级中心 → 升级洞察」页签，自上而下三个区块：
1. 升级顾问：选项目 + 选版本 → 点「运行顾问」（按钮只对有权角色显示）。结果含风险提示、破坏性变更清单、项目画像和一句总结论。
2. 排窗推荐：默认进入页签时自动拉取。每行一个候选时间窗，标了该窗口已占用的批次数，绿徽章=推荐窗口，行尾提示会说明金丝雀在该窗口放几只合适。
3. 骤降归因：列出升级前后通过率对比（升级前/后的样本数与成功率、骤降点数）和每行的处置建议。


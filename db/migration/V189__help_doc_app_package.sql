## 这一页能做什么
登记被测 App 的「包档案」（应用名+包名+版本+平台），并上传 APK/HAP 安装包归档。用例里的安装、卸载、版本对账步骤只按「包名+版本」引用这里的档案，不需要也不允许把下载路径写进步骤文本。入口：左侧菜单「执行中心 → 被测应用档案」。
## 怎么用
1. 先在页面顶部选择一个项目（档案按项目隔离，不同项目互不可见）；
2. 点「新建档案」填应用名称与包名（必填），版本可留空（未定版先建档）、平台从目录里选（留空=不限）；
3. 建档后在行上点「上传」选择安装包文件，上传进度实时可见；成功后该行的安装包列显示「已归档」并带体积与摘要前缀；
4. 换了新版安装包：重新建档（同包名同版本=覆盖留痕）或改版本建档后各自上传，历史档案按需删除即可（安装包随档案一并清理）。
## 操作背后系统做了什么
- 安装包归档到对象存储并按项目隔离；上传时系统实测文件体积与 SHA-256 摘要，以实测值登记（不是浏览器报的数），防止半成品/篡改包混入。
- 超过大小上限的包会被直接拒绝并给出说明原因的提示（上限是系统配置，管理员调高即热更生效，无需重启）；同档案重传成功后旧包立即清理，不留孤儿文件占盘。
- 任务执行时，安装步骤由服务端签发一次性下载地址传达到执行侧，执行侧下载后先按档案登记的摘要对账，对不上=包不完整，立刻失败并说明原因——不会出现装了半包或装了错包还显示通过。
- 版本对账（verifyVersion）用档案里的版本与设备现装版本比对：不一致或设备上没装会被拦下并点名差异，杜绝「跑的是旧包却当新包结论」。
## 常见问题
- 上传被拒「超过大小上限」怎么办？——先确认包是否传错；确需大包请管理员在系统配置调高上限，保存即生效。
- 删除档案会影响正在跑的任务吗？——不影响已派发会话；后续派发引用该包名的安装步骤会快速失败并提示档案不存在。
- CI 出的包怎么进来？——本期先走本页手动上传；开放接口（工件直传）为二期预留，档案结构已兼容。
- 「权限规则引用」是干什么的？——预授权弹框场景的规则键登记位；本期仅登记展示，派发侧消费随权限规则面接入。

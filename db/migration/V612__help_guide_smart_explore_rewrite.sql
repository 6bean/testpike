## 怎么用（按操作顺序）
1. **进页面**：左侧菜单「造数与资产 → 智能探索」。列表展示每次探索会话的探索目标、起点形态、状态、步数/页面、成本；条数多时翻页查看，点「刷新」重读最新状态。
2. **新建探索**：点「新建探索」打开「新建自主探索」窗口，先选起点形态：「网页（URL 起点）」填起始 URL；「App（移动形态）」选被测应用包（候选来自「被测应用包档案」，未建档可直接输入包名），并且必须选目标环境——只有开发/测试环境可选，生产环境禁入。
3. **决定带不带身份进门**：网页形态在起始 URL 下方选「登录态（可选）」——候选=本项目已登记的登录态（访问令牌 / Cookie / 浏览器快照三种重放方式），选中后探索浏览器以该身份直接进入站点，不选=匿名探索，遇到需要登录的页面会如实留在登录页。App 形态改选「预置测试账号」——引用凭据保险箱里的账号，只传引用键名，口令全程加密不回显。两套来源互不替代，机密实值都不随探索任务下发。
4. **查看预估**：点「查看预估」，看到预估 token、预估成本与步数上限后再点「确认发起」。预估快照随会话固化，实际消耗以执行为准。
5. **看过程**：发起成功提示「探索会话已创建，正在后台执行」。打开详情，步骤时间线会逐条追加——每步有步骤号、动作、是否跑通；点「取证」查看该步截图，展开「LLM 思考」「动作 JSON」「执行结果」核对它当时为什么这么点。
6. **止损与清理**：不想跑了点「终止探索」，会话软终止为已取消、证据保留；「删除」清理会话记录，证据对象存储不受影响。
7. **转正式用例**：详情页勾选标了「跑通」的步骤，点「转正式用例」，确认后提示「已生成 N 条用例（待评审）」——转正不绕质量门，评审通过才成为正式用例。

## 操作背后系统做了什么
- 自主循环：系统按你填的目标打开起点，每一步先观察当前页面，再由模型决定下一个动作（点击、输入、等待、跳转），生成动作 JSON 交给执行器运行，截图与判定结果回写成一步；循环推进直到目标完成、步数用尽或成本触顶。
- 预算上限保护：发起前固化的预估就是本次上限，实际成本触顶时系统自动停止收尾，状态标为「预算熔断」，已产出的步骤与证据照常保留——不会越跑越贵。
- 环境与安全边界：App 探索只允许开发/测试环境，生产地址在后端白名单处即拦截；登录态与测试账号只以引用或可重放材料形式下发，机密实值不进任务报文、不在页面回显。
- 证据固化：每步截图与协议内容随步落盘，事后不依赖原环境即可回放核对；「删除」只清理会话记录，不触碰证据存储对象。
- 结果去向：探索产出的用例统一落待评审队列，采纳与否由人决定，系统不会替你自动加用例。


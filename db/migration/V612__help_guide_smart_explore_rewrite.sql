- **登录态下拉里没有候选？**——先到「造数与资产 → 登录态账本」页登记一条，或从已登录浏览器采集一份，回到本页重新打开新建弹窗即可看到。
- **探索过程一直停在登录页？**——多半是所选登录态已过期：到登录态账本页对它「立即测试」确认失效，重新采集后再发起探索即可；会话材料过期不会被静默冒充成功。

## 怎么用
1. 弹窗里勾选要跑的组合：候选面来自引擎中心已启用引擎×其声明的平台/机型面×设备台账，同一组合自动去重；
2. 可先点「智能推荐」让系统建议一组组合（默认关，见「机型矩阵智能抽样」一章），推荐只是预勾选，仍由你确认；
3. 点「成本预检」看扇出任务数、每任务分钟、队列前待派发、预计排队分钟与预计开跑时间，以及单用例组合上限；
4. 点「确认扇出派发」自动生成一个批次（批次名默认「机型矩阵扇出批」）并按组合逐一经既有派发链入队，成功后弹窗给出直达该批次的入口。

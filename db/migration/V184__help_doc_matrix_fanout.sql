- 派发前有闸：组合越出该引擎描述符声明的平台面/机型面会被秒拒（不去烧执行器会话）；组合数有单用例硬上限（默认 12，系统设置调高即热更生效），超限点名上限；用例目标不是 APP/多端或没有 APP 步骤也会被拒绝并说明原因单。

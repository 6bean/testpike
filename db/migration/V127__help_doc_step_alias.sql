## 这一页能做什么
给步骤里的「引用」起一个易读名字：在来源处登记（比如把某一步叫「创建订单」、把某个提取出来的字段叫「订单号」），之后引用就按名字写。将来步骤挪了位置、字段换了路径，只需要在别名登记的这一行改指向，用例里的引用全部照常生效、不断链。

## 怎么用（三个入口）
1. **提取行名称框**：步骤里勾选「提取」时，行上有个名称输入框——填个易读名即登记该字段的别名。
2. **步骤树重命名**：用例详情的步骤排序面板里，每个步骤右侧有「重命名」按钮，给整步起个业务名（如「登录」「下单」），即步骤别名。
3. **引用分组复制**：「角色与绑定」页的「引用变量别名」分组列出当前项目已登记的全部别名，点「复制」粘到步骤的「值」字段即可，全程不用手写任何配置文件。

## 操作背后系统做了什么
- 别名只是「昵称」：引用保存时，服务端先查别名表，把名字翻译成真实地址（步骤序号或数据路径）；查不到就按原来的直址写法处理，两种写法共存互不影响。
- 登记那一刻做冲突校验：同一项目内重名、占用系统保留词（如 RUN、global）、或长得像纯数字步骤序号的，都会被中文点名拒绝，照着提示改名再存即可。
- 变动只改一行：步骤先后顺序漂移或提取路径改版时，把别名指向改成新地址，用例引用一处都不用动——这就是别名解决的核心问题。

## 常见问题
- 别名会影响已有用例吗？——不会。没用别名的直址引用照常运行，行为零变化。
- 别名的作用范围？——项目内。每个项目的别名表互相独立。
- 什么时候值得起别名？——引用会被多处用到、或步骤顺序/接口字段可能调整时；一次性的小引用直址写就好。

## 这一页能做什么
当 APP 用例被广告、升级提示、权限申请一类的弹框挡住而失败时，系统可以把失败瞬间留存的监看画面交给视觉模型，归纳出一条「遇到这种弹框就点这个按钮」的处理规则草稿——但草稿绝不自动生效，必须在这里由人批准后入库。入口：左侧菜单「执行中心 → 弹窗规则审批台」。
## 怎么用
1. 先在页面顶部选择一个项目（规则按项目隔离，不同项目互不可见）；
2. 点「从失败任务自学」，在对话框里选一个最近失败或超时的执行任务，系统读取该任务失败时留存的监看画面开始识别；
3. 识别完成后，新草稿出现在列表中（状态=待审）；点行首箭头可展开查看规则内容（检测条件+处置动作的交换格式）；
4. 逐条审阅后点「批准入库」或「驳回」：批准的成为正式规则并留痕；驳回只翻状态留痕，规则内容不入库，之后可以重新发起自学；
5. 用状态下拉筛选「待审」可以只看还没处理过的草稿。
## 操作背后系统做了什么
- 送识别前，系统先做两道保护：引用了登录凭据等敏感步骤的画面被物理剔除，绝不会送进模型；功能开关（默认关闭）与权限键双闸才放行发起，防止误触消耗。
- 识别结果先过结构闸：检测条件和处置动作不齐全的残缺规则直接被拒，不进待审列表——你看到的每一条草稿都是格式完整的。
- 批准是唯一入库通道，且需要审批权限；同一条草稿被两人先后点批准时，后一次会被拦下并说明已被处理，不会重复入库。
- 草稿的归属项目以任务实际归属为准（系统按来源任务反查），发起时选错项目也改不了数据归属。
## 常见问题
- 点「自学」提示功能未开启？——这是 AI 消耗功能，默认关闭；请管理员在「系统设置 → APP 自动化」开启后再来。
- 提示没有可用画面？——监看画面只在内存短窗口内留存，失败后要尽快发起自学；太久之前的任务画面已过期。
- 入库后的规则什么时候生效？——入库形成正式规则库，执行时自动规避弹框的消费面随派发侧接入；本页对已入库规则只读留痕。
- 驳回后能改吗？——驳回是留痕翻状态，不删除内容；需要修正重新发起自学即可。

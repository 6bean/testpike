## 这一页能做什么
在用例的脚本编辑器里，输入一个已结束的移动端执行任务号，系统会读取该任务采集到的操作录制事件（点按、滑动、返回等），自动反推成一串 APP 操作步骤草稿。草稿默认不生效：你先预览逐步核对，勾选确认后才并入用例脚本；不要的可整单驳回。整个过程是「先预览、后人批」两道质量门，机器绝不替你写库。

## 怎么用
入口：用例详情 → 「脚本」区 → 「树编辑」→ 工具条「录制转流程」。
1. 前提：用例的自动化目标已选「移动 App」或「小程序」，且已选好执行引擎。
2. 在弹窗里填入一个已经跑完、且带回录制事件的执行任务号，点「载入录制事件」。
3. 载入成功后显示事件条数与采集档位；如有个别事件无法识别会被单独丢弃，档位旁会提示丢弃条数，不影响其余事件。
4. 填一个草稿标题，点「反推步骤草稿」，系统按该引擎能力生成步骤列表（默认全选）。
5. 逐条勾选核对后点「勾选入库」并入脚本；点「驳回」则整单作废留痕，脚本不受任何影响。
6. 弹窗下方会列出该用例已有的待处理草稿，可随时「预览」回看或「驳回」。

## 操作背后系统做了什么
- 载入只读取该任务的录制事件原样呈现，不产生任何写入。
- 反推前先做三道闸：功能开关未开启时直接拒绝并说明原因、不发起任何模型调用；任务不属于当前项目会被拒绝；引擎做不到的动作会被裁掉，模型应答里混入能力之外的动作时整单拒绝。
- 入库是草稿转正的唯一通道：转正走脚本既有的保存校验链（版本保护、词法闸全部生效），他人已改会提示刷新重试，绝不静默覆盖；驳回只翻状态留痕，脚本零触碰。
- 这个功能默认关闭：未开启时弹窗内会出现提示卡与「去系统设置」直达入口，由管理员在「系统设置 → APP 自动化」开启后重试。

## 常见问题
- 载入后提示没有录制事件？——该任务执行时所在设备或引擎未采到操作事件（部分引擎形态暂无事件流），换一个带回录制事件的任务号。
- 反推出来的步骤为空？——录制事件可能都不属于该引擎能表达的动词，或描述超出引擎能力，换任务或换引擎。
- 入库后发现有几步不对？——并入后仍是普通步骤，直接在树编辑器里改字段或删步，保存即生效。

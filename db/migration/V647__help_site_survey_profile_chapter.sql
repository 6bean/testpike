「测绘此页」一次只把一个页面的元素存进档案，站点页面一多（比如上百页的频道站）就逐页点不过来。整站测绘解决这件事：你只要填一个起始地址（如 https://example.com/pr/），系统就顺着页面里的链接逐页打开、自动递归，把整站发现的可点元素批量登记到「页面元素库」的候选里，由你确认后供测试用例引用。站点档案把这套采集规则（起始地址、排除清单、预算）存下来，随时可以再次发起，每一轮都有可回看的测绘记录。解决的典型业务问题：新站点接手时批量建档、页面改版后全量刷新锚、同一站点的采集范围团队共用一份配置而不是每人重配。


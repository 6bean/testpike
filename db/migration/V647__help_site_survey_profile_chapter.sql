- **「进程详情」打开是空的或者提示超期？**——两种设计内情形：记录在执行会话建立前就结束了（本来就没有过程记录，页面已注明）；或事件明细已超过保留期（缺省 90 天，参数 element.survey-site.event-retention-days，可在「系统设置 → 参数设置」调长，此后新记录完整保留）。

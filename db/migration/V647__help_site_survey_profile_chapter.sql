## 怎么用（按操作顺序）
1. **建档案**：「页面元素库 → 站点档案 → 新建档案」。档案名称与起始地址必填，缺了会被点名哪个字段没填；可选设置「路径排除清单」（每行一条通配，如 /admin/*，命中的链接不会被访问）、「忽略参数」（地址只差翻页/时间参数时视为同一个页面）、「登录态」（从登录态配置里选取，不能手动输入）、「动词护栏」（链接命中「删除、导出、logout」等词语时对应页面不会被访问）与「预算覆盖」（最多页面数、最大递归深度、页面间隔毫秒、总时限秒等六项，留空用系统缺省）。保存后提示 站点档案「{名称}」已保存。
2. **发起测绘**：档案行点「测绘」。发起后提示 已发起整站测绘：{名称}，档案行亮起「整站测绘进行中」徽标，「测绘记录」清单新增一行，状态会自己从「进行中」走到「已完成 / 部分完成 / 失败 / 已取消」，不需要手动刷新页面。
3. **看过程**：测绘记录行点「进程详情」打开回放窗，逐页显示打开了哪个页面、入账几枚元素、哪些链接被跳过或折叠；进行中的记录实时跟随新帧，已终态的记录可随时整体回看，记录较多时点「加载更多过程记录」继续取。把当前页面地址复制给同事，对方能直接打开同一条记录的详情。
4. **核对入库**：测绘入账的元素是「候选」状态，元素库列表「页面」列能看到按页分布；核对后点「确认入库」转为「已确认」，用例引用的是已确认档案；拿不准的「标记待复核」，不要的「退役」。
5. **再测绘与对账**：站点改版后对同一档案再点「测绘」。新出现的元素照常进候选；测绘记录里的「命名待复核」列提示这轮有多少元素名称需要你过目。

## 操作背后系统做了什么
- 范围规则：只访问与起始地址同源（同协议同域名）的链接，并按路径段对齐——起始地址在 /pr/ 段就深钻 /pr/ 段；同站的其他首段（如 /md/）标为邻接段：不深钻，但每个段的命中数会记进过程帧，能在「进程详情」里核对。
- 去重与折叠：地址先做归一化（忽略翻页/时间类参数），能折叠为同一模板页的地址族（如 /order/1、/order/2 这类）默认只采集第一枚（同类页面采集上限，参数 element.survey-site.per-template-cap，缺省 1），所以列表翻页不会把同一页重复采进账。
- 只打开、不操作：全过程只打开页面，不点击按钮、不提交表单；动词护栏提前排除疑似有副作用的链接，被排除与被跳过的链接逐条计数，在「进程详情」可核对。
- 登录墙如实处理：某页跳到了登录页（登录墙）时该页不入账；这类页占到一半以上，整轮记为失败或部分完成，不会把没扫到的页面算成扫过。
- 生产域名保护：对生产域名发起整站测绘默认被拦下，提示会列出命中的域名；确认要扫时，在「系统设置 → 参数设置」把参数 element.survey-site.allow-prod 打开（出厂为关）。整站测绘总开关 element.survey-site.enabled 默认开，关闭时发起入口会说明在哪里重新开启；单页「测绘此页」不受影响。
- 预算与热更：最多页面数（缺省 100）、最大递归深度（缺省 6）、页面间隔（缺省 800 毫秒）、总时限（缺省 1800 秒）、单页链接上限（缺省 60）、同类页面上限（缺省 1）都在「系统设置 → 参数设置」以 element.survey-site. 为前缀管理，保存即生效；档案级预算覆盖优先于系统缺省。预算或时限用完 = 部分完成，已采集结果保留。
- 过程留痕：进行中的跟随窗按 element.survey-site.tail-cap（缺省 400 条）保留最近事件；每条记录落库的过程事件上限 element.survey-site.history-frame-cap（缺省 2000 条），超出时中间段截尾并在回放里注明被截条数；事件明细保留 element.survey-site.event-retention-days（缺省 90）天，超期后回放入口会说明保留期限与调整位置，不会给你一个空白窗。

## 常见问题

新建站点档案（起始地址＋范围/排除/预算）→ 档案行点「测绘」发起 → 系统在同站点路径范围内逐页打开（跳掉被排除与被动词护栏命中的链接，同类模板页折叠去重）→ 每页元素登记为「候选」并留下逐页过程帧 → 「进程详情」随时回放过程 → 在元素库按「页面」分组核对，点「确认入库」转正 → 用例引用已确认的锚。

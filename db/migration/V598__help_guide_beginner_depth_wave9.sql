## 怎么用（按操作顺序）
1. **生成脚本**：打开用例详情页的「脚本」页签，点「生成」。系统把自然语言步骤编译成结构化动作序列（打开页面、点击、输入、断言），元素定位采用多策略降级：页面元素标识优先，其次可见文本，最后路径。生成时会参考你们登记过的脚本规范。
